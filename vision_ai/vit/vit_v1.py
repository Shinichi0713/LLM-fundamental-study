class MLP(nn.Module):
  def __init__(self, in_dim, hidden_dim, out_dim, dropout=0.0):
      super().__init__()
      self.fc1 = nn.Linear(in_dim, hidden_dim)
      self.fc2 = nn.Linear(hidden_dim, out_dim)
      self.act = nn.GELU()
      self.dropout = nn.Dropout(dropout)
  def forward(self, x):
      x = self.fc1(x)
      x = self.act(x)
      x = self.dropout(x)
      x = self.fc2(x)
      x = self.dropout(x)
      return x

class TransformerEncoderBlock(nn.Module):
  def __init__(self, in_dim, num_heads, mlp_ratio=4.0, dropout=0.0):
    super().__init__()
    self.norm1 = nn.LayerNorm(in_dim)
    self.attn = nn.MultiheadAttention(in_dim, num_heads=num_heads, dropout=dropout)
    self.norm2 = nn.LayerNorm(in_dim)
    self.mlp = MLP(in_dim, int(in_dim * mlp_ratio), in_dim, dropout=dropout)
    self.dropout = nn.Dropout(dropout)

  def forward(self, x):
    x_norm = self.norm1(x)
    attn_out, _ = self.attn(x_norm, x_norm, x_norm)
    x = x + self.dropout(attn_out)
    x_norm = self.norm2(x)
    x = x + self.mlp(x_norm)
    return x


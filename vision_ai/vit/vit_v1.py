def train_one_epoch(model, loader, optimizer, criterion, device, epoch, scheduler: Optional[object]=None):
    model.train()
    running_loss = 0.0
    total = 0
    correct = 0
    start = time.time()
    for i, (imgs, labels) in enumerate(loader):
        imgs = imgs.to(device)
        labels = labels.to(device)
        logits = model(imgs)
        loss = criterion(logits, labels)

        optimizer.zero_grad()
        loss.backward()
        optimizer.step()
        if scheduler is not None:
            scheduler.step()

        running_loss += loss.item()*imgs.size(0)
        preds = logits.argmax(dim=1)
        total += imgs.size(0)
        correct += (preds == labels).sum().item()

        if (i+1) % 50 == 0:
            print(f"[Epoch {epoch}] Step {i+1}/{len(loader)} loss {running_loss/total:.4f} acc {100.*correct/total:.2f}%")

    epoch_loss = running_loss / total
    epoch_acc = 100.*correct/total
    elapsed = time.time() - start
    print(f"Epoch {epoch} TRAIN Loss={epoch_loss:.4f} Acc={epoch_acc:.2f}% Elapsed={elapsed:.1f}s")
    return epoch_loss, epoch_acc

def evaluate(model, loader, criterion, device):
    model.eval()
    running_loss = 0.0
    total = 0
    correct = 0
    with torch.no_grad():
        for imgs, labels in loader:
            imgs = imgs.to(device)
            labels = labels.to(device)
            logits = model(imgs)
            loss = criterion(logits, labels)
            running_loss += loss.item()*imgs.size(0)
            preds = logits.argmax(dim=1)
            total += imgs.size(0)
            correct += (preds == labels).sum().item()
    return running_loss/total, 100.*correct/total


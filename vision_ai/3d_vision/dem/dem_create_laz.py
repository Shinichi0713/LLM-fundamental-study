import os
import laspy
import numpy as np
import rasterio
from rasterio.transform import from_origin
import matplotlib.pyplot as plt

laz_file = "08ME3562.las"

# 3. LAZファイルの読み込み
las = laspy.read(laz_file)

# 座標の取得
x = las.x
y = las.y

# RGB情報の取得（16bitから8bitへ変換）
# ※データによってはRGBがなくIntensity（反射強度）のみの場合もあります
r = (las.red / 256).astype(np.uint8)
g = (las.green / 256).astype(np.uint8)
b = (las.blue / 256).astype(np.uint8)

# 4. 2Dグリッド（ピクセル）の設定
pixel_size = 1.0  # 1ピクセル = 1m （処理を軽量化するため1mに設定）

x_min, x_max = np.min(x), np.max(x)
y_min, y_max = np.min(y), np.max(y)

width = int(np.ceil((x_max - x_min) / pixel_size))
height = int(np.ceil((y_max - y_min) / pixel_size))

# ピクセルインデックスの計算
col_idx = np.floor((x - x_min) / pixel_size).astype(int)
row_idx = np.floor((y_max - y) / pixel_size).astype(int)

# 範囲外のインデックスを制限
col_idx = np.clip(col_idx, 0, width - 1)
row_idx = np.clip(row_idx, 0, height - 1)

# 5. グリッドへRGBを配置
ortho_image = np.zeros((height, width, 3), dtype=np.uint8)

# 点群の色を割り当て
ortho_image[row_idx, col_idx, 0] = r
ortho_image[row_idx, col_idx, 1] = g
ortho_image[row_idx, col_idx, 2] = b

# 6. GeoTIFFとして保存
transform = from_origin(x_min, y_max, pixel_size, pixel_size)
output_tif = "output_ortho.tif"

with rasterio.open(
    output_tif,
    'w',
    driver='GTiff',
    height=height,
    width=width,
    count=3,
    dtype=ortho_image.dtype,
    crs=las.header.parse_crs() if las.header.parse_crs() else "EPSG:2992", # フォールバック座標系
    transform=transform,
) as dst:
    dst.write(ortho_image[:, :, 0], 1)
    dst.write(ortho_image[:, :, 1], 2)
    dst.write(ortho_image[:, :, 2], 3)

print("GeoTIFFの生成が完了しました！")

# 7. 生成したオルソ画像のプレビュー表示
plt.figure(figsize=(10, 10))
plt.imshow(ortho_image)
plt.title("Generated Ortho Image from LAZ")
plt.axis('off')
plt.show()

import laspy
import numpy as np
import rasterio
from rasterio.transform import from_origin
import matplotlib.pyplot as plt

# 1. LAS/LAZファイルの読み込み
las_file = "08ME3562.las"  # または sample.laz
las = laspy.read(las_file)

# 2. 地表面（Ground: Classification 2）の点を抽出
# ※もし地表分類が付与されていないデータの場合は、全点 (las.z) を使用します
ground_mask = (las.classification == 2)

if np.sum(ground_mask) > 0:
    print(f"地表点（Ground）を抽出しました: {np.sum(ground_mask):,} 点")
    x = las.x[ground_mask]
    y = las.y[ground_mask]
    z = las.z[ground_mask]
else:
    print("地表分類タグが見つかりませんでした。全点群を使用してDEMを生成します。")
    x, y, z = las.x, las.y, las.z

# 3. 2Dグリッド（DEM）の設定
pixel_size = 1.0  # DEMの解像度（1ピクセル = 1m）

x_min, x_max = np.min(x), np.max(x)
y_min, y_max = np.min(y), np.max(y)

width = int(np.ceil((x_max - x_min) / pixel_size))
height = int(np.ceil((y_max - y_min) / pixel_size))

# ピクセル座標の計算
col_idx = np.floor((x - x_min) / pixel_size).astype(int)
row_idx = np.floor((y_max - y) / pixel_size).astype(int)

col_idx = np.clip(col_idx, 0, width - 1)
row_idx = np.clip(row_idx, 0, height - 1)

# 4. グリッドへの標高値（Z値）の割り当て
# 初期値はNaN（データなし）に設定
dem = np.full((height, width), np.nan, dtype=np.float32)

# 各ピクセル内で「最も標高が低い点（Minimum Z）」を採用して地表高とする
# ※単純な上書きではなく、同じセルに複数点ある場合の統計値をとります
for r, c, z_val in zip(row_idx, col_idx, z):
    if np.isnan(dem[r, c]) or z_val < dem[r, c]:
        dem[r, c] = z_val

# 5. 空白セル（データのない穴）の単純補間（Nearest Neighbor）
# 点群の隙間がある場合は近傍の値で埋める処理
nan_mask = np.isnan(dem)
if np.any(nan_mask):
    from scipy.ndimage import distance_transform_edt
    indices = distance_transform_edt(nan_mask, return_distances=False, return_indices=True)
    dem = dem[tuple(indices)]

# 6. GeoTIFF形式でDEMを保存
transform = from_origin(x_min, y_max, pixel_size, pixel_size)
output_dem_tif = "output_dem.tif"

with rasterio.open(
    output_dem_tif,
    'w',
    driver='GTiff',
    height=height,
    width=width,
    count=1,
    dtype=dem.dtype,
    crs=las.header.parse_crs() if las.header.parse_crs() else "EPSG:6676",
    transform=transform,
    nodata=-9999.0
) as dst:
    dst.write(dem, 1)

print(f"DEM（GeoTIFF）の保存が完了しました: {output_dem_tif}")

# 7. DEMのプレビュー表示（カラーマップによる起伏可視化）
plt.figure(figsize=(10, 8))
plt.imshow(dem, cmap='terrain')
plt.colorbar(label='Elevation (m)')
plt.title("Generated DEM (Digital Elevation Model)")
plt.axis('off')
plt.show()


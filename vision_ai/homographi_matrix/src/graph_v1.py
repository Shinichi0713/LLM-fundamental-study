import matplotlib.pyplot as plt
import networkx as nx
import random

# 無向グラフの作成
G = nx.Graph()

# ノード数を増やす（例：10ノード）
num_nodes = 10
for i in range(1, num_nodes + 1):
    G.add_node(f"User_{i}")

# 辺をランダムに追加（例：各ノードから2〜3本の辺）
for i in range(1, num_nodes + 1):
    # 各ノードから2〜3本の辺を追加
    num_edges_from_node = random.randint(2, 3)
    # 自分自身と重複を避けて接続先を選ぶ
    possible_targets = [j for j in range(1, num_nodes + 1) if j != i]
    targets = random.sample(possible_targets, min(num_edges_from_node, len(possible_targets)))
    for t in targets:
        # 既に辺がある場合は追加しない（無向なので片方だけ見ればよい）
        if not G.has_edge(f"User_{i}", f"User_{t}"):
            G.add_edge(f"User_{i}", f"User_{t}", label="Friend")

# 描画設定（サイズを大きくする）
pos = nx.spring_layout(G, seed=42)  # 再現性のためにseedを固定
plt.figure(figsize=(10, 8))

# ノードと辺を描画
nx.draw_networkx_nodes(G, pos, node_size=800, node_color="lightblue")
nx.draw_networkx_edges(G, pos, width=2, edge_color="gray")

# ノードラベル

import matplotlib.pyplot as plt
import networkx as nx

# 1. グラフの構築（ランダムグラフの生成、または手動での追加）
# ここでは10個のノードを持つランダムなグラフ（Erdős-Rényiモデル）を作成します
G = nx.erdos_renyi_graph(n=10, p=0.3, seed=42)

# ノード間の接続が担保されていない場合に備えて連結成分を確認
if not nx.is_connected(G):
    # 最大の連結成分を取得して再構築
    largest_cc = max(nx.connected_components(G), key=len)
    G = G.subgraph(largest_cc).copy()

# 2. パスを探すスタートとゴールのノードを指定
start_node = list(G.nodes())[0]
target_node = list(G.nodes())[-1]

# 最短パス（Shortest Path）の計算
path = nx.shortest_path(G, source=start_node, target=target_node)
print(f"探索されたパス: {path}")

# 3. パスに含まれるエッジ（辺）のリストを作成
path_edges = list(zip(path[:-1], path[1:]))

# 4. 可視化の設定
plt.figure(figsize=(8, 6))

# ノードの配置（レイアウト）を決める
pos = nx.spring_layout(G, seed=42)

# --- 基本のグラフを描画 ---
# 全体のノードを描画
nx.draw_networkx_nodes(G, pos, node_color="lightblue", node_size=700)
# 全体のエッジを描画
nx.draw_networkx_edges(G, pos, edge_color="gray", width=1.5, alpha=0.6)
# ノードのラベルを描画
nx.draw_networkx_labels(G, pos, font_size=12, font_family="sans-serif")

# --- パス（通過ルート）をハイライト描画 ---
# パス上のノードを強調
nx.draw_networkx_nodes(
    G, pos, nodelist=path, node_color="orange", node_size=800
)
# スタートとゴールをさらに強調
nx.draw_networkx_nodes(
    G, pos, nodelist=[start_node], node_color="green", node_size=900
)
nx.draw_networkx_nodes(
    G, pos, nodelist=[target_node], node_color="red", node_size=900
)

# パス上のエッジを強調
nx.draw_networkx_edges(
    G, pos, edgelist=path_edges, edge_color="red", width=3.5
)

# 凡例・タイトルの設定
plt.title(
    f"Graph Path Visualization ({start_node} -> {target_node})", fontsize=14
)
plt.axis("off")  # 軸を非表示にする
plt.tight_layout()

# 表示
plt.show()

import matplotlib.pyplot as plt
import networkx as nx

# 1. 配送ネットワーク（グラフ）の構築
G = nx.Graph()

# 拠店（ノード）とルート（エッジ）の定義
edges = [
    ("Tokyo", "Saitama"),
    ("Saitama", "Gunma"),
    ("Gunma", "Tochigi"),
    ("Tochigi", "Ibaraki"),
    ("Ibaraki", "Saitama"),  # ここでサイクルが形成される (Saitama-Gunma-Tochigi-Ibaraki-Saitama)
    ("Tokyo", "Chiba"),
    ("Chiba", "Ibaraki"),  # ここでも別のサイクルが形成される
    ("Tokyo", "Kanagawa"),  # サイクルに含まれない枝ルート
]

G.add_edges_from(edges)

# 2. サイクル（閉路）の検出
# nx.cycle_basis は無向グラフの基底サイクル（最小単位のサイクルの組）を返します
cycles = nx.cycle_basis(G)

print(f"検出されたサイクルの数: {len(cycles)}")
for i, c in enumerate(cycles):
    # 見やすさのために先頭のノードを末尾にも追加して表示 (例: A -> B -> C -> A)
    cycle_path = c + [c[0]]
    print(f"  サイクル {i + 1}: {' -> '.join(cycle_path)}")

# 可視化対象とするサイクルを1つ選択（ここでは最初のサイクル）
target_cycle = cycles[0] if cycles else []

# サイクルに含まれるエッジ（辺）のペアリストを作成
cycle_edges = []
if target_cycle:
    cycle_nodes_seq = target_cycle + [target_cycle[0]]
    cycle_edges = list(zip(cycle_nodes_seq[:-1], cycle_nodes_seq[1:]))

# 3. 可視化の設定
plt.figure(figsize=(9, 7))

# レイアウトの固定（表示の再現性を保つためにseedを設定）
pos = nx.spring_layout(G, seed=15)

# --- A. 背景となる全体のグラフを描画 ---
# 通常のノード
nx.draw_networkx_nodes(
    G, pos, node_color="#E0E0E0", node_size=1200, edgecolors="gray"
)
# 通常のエッジ
nx.draw_networkx_edges(
    G, pos, edge_color="#B0B0B0", width=1.5, style="dashed"
)
# ノードラベル（拠点名）
nx.draw_networkx_labels(
    G, pos, font_size=10, font_family="sans-serif", font_weight="bold"
)

# --- B. 検出されたサイクルを強烈にハイライト ---
if target_cycle:
    # サイクルを構成するノードを強調（鮮やかなオレンジ）
    nx.draw_networkx_nodes(
        G,
        pos,
        nodelist=target_cycle,
        node_color="#FF9800",
        node_size=1400,
        edgecolors="#E65100",
        linewidths=2,
    )

    # サイクルを構成するエッジを強調（太い赤線）
    nx.draw_networkx_edges(
        G, pos, edgelist=cycle_edges, edge_color="#D32F2F", width=4.0
    )

# グラフタイトル・描画設定
plt.title(
    "Delivery Network: Cycle Detection Visualization",
    fontsize=14,
    pad=15,
)
plt.axis("off")
plt.tight_layout()

plt.show()

import networkx as nx
import matplotlib.pyplot as plt
from networkx.drawing.nx_pydot import graphviz_layout

def visualize_tree_structure():
    # 1. 木（Tree）グラフの構築
    # ここでは手動でエッジを追加して、シンプルな木を作成します。
    # 木の定義：連結でサイクルがないグラフ。
    G = nx.Graph()

    # エッジのリスト (親, 子)
    # 根（Root）を 'Root' とします。
    tree_edges = [
        ('Root', 'Child A'),
        ('Root', 'Child B'),
        ('Root', 'Child C'),
        ('Child A', 'Leaf A1'),
        ('Child A', 'Leaf A2'),
        ('Child B', 'Leaf B1'),
        ('Child C', 'Leaf C1'),
        ('Child C', 'Leaf C2'),
        ('Child C', 'Leaf C3'),
        ('Leaf A2', 'Sub-Leaf A2-1') # さらに深く
    ]
    G.add_edges_from(tree_edges)

    # 木であることを確認（デバッグ用）
    if not nx.is_tree(G):
        print("警告: 作成されたグラフは木ではありません。")
        return

    # 2. 階層型レイアウトの計算
    # Graphvizの 'dot' レイアウトエンジンを使用して、親から子へのきれいな階層を計算します。
    # ※この機能を使用するには、システムにGraphviz本体のインストールが必要です。
    try:
        # root引数で根ノードを指定すると、そこを起点に階層化されます。
        pos = graphviz_layout(G, prog='dot', root='Root')
    except ImportError:
        print("エラー: pydot または Graphviz が見つかりません。")
        print("通常のspringレイアウトで代用しますが、階層にはなりません。")
        pos = nx.spring_layout(G) # 代替案

    # 3. 可視化の設定
    plt.figure(figsize=(12, 8))

    # ノードの種類ごとに色を変えるためのリスト作成
    node_colors = []
    for node in G.nodes():
        if node == 'Root':
            node_colors.append('#FF5722') # 根：鮮やかなオレンジ
        elif G.degree(node) == 1 and node != 'Root':
            node_colors.append('#8BC34A') # 葉（末端）：黄緑
        else:
            node_colors.append('#03A9F4') # 中間ノード：水色

    # --- 描画 ---
    # エッジ（辺）の描画
    nx.draw_networkx_edges(G, pos, edge_color='#BDBDBD', width=2)

    # ノード（頂点）の描画
    nx.draw_networkx_nodes(
        G, pos,
        node_color=node_colors,
        node_size=2000,
        edgecolors='white', # ノードの枠線
        linewidths=2,
        alpha=0.9
    )

    # ラベル（ノード名）の描画
    nx.draw_networkx_labels(
        G, pos,
        font_size=10,
        font_family='sans-serif',
        font_weight='bold'
    )

    # 全体の設定
    plt.title("Tree Structure Visualization (Graphviz DOT Layout)", fontsize=16)
    plt.axis('off') # 軸を非表示
    plt.tight_layout()

    # 表示
    plt.show()

# 関数を実行
if __name__ == "__main__":
    visualize_tree_structure()


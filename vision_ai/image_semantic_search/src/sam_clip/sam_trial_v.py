def show_anns(anns, ax):
    """生成されたすべてのマスクをランダムな色で重畳表示する関数"""
    if len(anns) == 0:
        return
    sorted_anns = sorted(anns, key=(lambda x: x['area']), reverse=True)
    ax.set_autoscale_on(False)

    img = np.ones((sorted_anns[0]['segmentation'].shape[0], sorted_anns[0]['segmentation'].shape[1], 4))
    img[:, :, 3] = 0
    for ann in sorted_anns:
        m = ann['segmentation']
        color_mask = np.concatenate([np.random.random(3), [0.6]]) # アルファ値0.6
        img[m] = color_mask
    ax.imshow(img)

def run_sam_standalone(image_path, sam_checkpoint, model_type="vit_b", output_path="sam_standalone_result.png"):
    # デバイスの設定
    device = "cuda" if torch.cuda.is_available() else "cpu"
    print(f"使用デバイス: {device}")

    # 1. 事前学習済みSAMモデルのロード（ファインチューニング前の公式重み）
    print("事前学習済みSAMモデルをロード中...")
    sam = sam_model_registry[model_type](checkpoint=sam_checkpoint)
    sam.to(device=device)

    # 2. 自動マスク生成クラスの初期化
    # (points_per_side などのパラメータで検知の細かさを制御可能)
    mask_generator = SamAutomaticMaskGenerator(
        model=sam,
        points_per_side=32,          # グリッドサンプリング点数 (大きくするとより細かく検出)
        pred_iou_thresh=0.88,        # マスク品質の閾値
        stability_score_thresh=0.95, # マスク安定性の閾値
        crop_n_layers=0,
    )

    # 3. 画像の読み込み
    if not os.path.exists(image_path):
        print(f"エラー: 画像ファイルが見つかりません ({image_path})")
        return

    image = cv2.imread(image_path)
    image = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)

    # 4. 全自動マスク生成の実行
    print("画像全体のマスクを自動生成中...")
    masks = mask_generator.generate(image)
    print(f"検出された合計マスク数: {len(masks)} 個")

    # 5. 可視化と結果の保存
    fig, axes = plt.subplots(1, 2, figsize=(16, 8))

    # 元画像
    axes[0].imshow(image)
    axes[0].set_title("Original Image")
    axes[0].axis('off')

    # SAM単体出力（全自動検知マスク）
    axes[1].imshow(image)
    show_anns(masks, axes[1])
    axes[1].set_title(f"Vanilla SAM Output\n({len(masks)} masks detected)")
    axes[1].axis('off')

    plt.tight_layout()
    plt.savefig(output_path, bbox_inches='tight', dpi=150)
    plt.close(fig)

    print(f"可視化結果を保存しました: {output_path}")


# 評価指標計算関数
def calculate_metrics(pred_mask, gt_mask):
    """
    pred_mask, gt_mask: 共に 2D numpy array (bool or uint8 0/1)
    """
    pred = (pred_mask > 0.5)
    gt = (gt_mask > 0.5)

    intersection = np.logical_and(pred, gt).sum()
    union = np.logical_or(pred, gt).sum()
    pred_sum = pred.sum()
    gt_sum = gt.sum()

    # Zero division 回避
    iou = intersection / union if union > 0 else 1.0 if pred_sum == 0 and gt_sum == 0 else 0.0
    precision = intersection / pred_sum if pred_sum > 0 else 1.0 if gt_sum == 0 else 0.0
    recall = intersection / gt_sum if gt_sum > 0 else 1.0 if pred_sum == 0 else 0.0

    return iou, precision, recall

def run_evaluation(val_list_path, img_dir, mask_dir, output_dir, text_prompt):
    os.makedirs(output_dir, exist_ok=True)

    # 1. 検証用リストのロード
    with open(val_list_path, 'r') as f:
        lines = [line.strip() for line in f if line.strip()]

    print(f"評価を開始します (対象画像数: {len(lines)} 枚, プロンプト: '{text_prompt}')")

    total_iou, total_precision, total_recall = 0.0, 0.0, 0.0

    plt.ioff() # 描画ウィンドウ非表示

    for idx, line in enumerate(lines):
        img_name, mask_name = line.split(',')
        img_path = os.path.join(img_dir, img_name)
        mask_path = os.path.join(mask_dir, mask_name)

        # 画像・マスクの読み込み
        orig_img = Image.open(img_path).convert('RGB')
        gt_mask = Image.open(mask_path).convert('L')
        gt_arr = (np.array(gt_mask) > 128).astype(np.uint8)

        # -------------------------------------------------------------
        # ※ 実際の実装ではここでモデルの forward(img, text_prompt) を行います。
        # ポック検証用ダミー処理（モデルからの予測マスク取得イメージ）
        # 実際には model.predict(orig_img, text_prompt) 等で得られた出力マスクを使用します。
        pred_arr = gt_arr.copy() # パイプライン確認用
        # -------------------------------------------------------------

        # 指標計算
        iou, prec, rec = calculate_metrics(pred_arr, gt_arr)
        total_iou += iou
        total_precision += prec
        total_recall += rec

        # 2. 定性評価用画像の可視化・保存
        fig, axes = plt.subplots(1, 3, figsize=(15, 5))

        # 元画像
        axes[0].imshow(orig_img)
        axes[0].set_title(f"Original Image ({img_name})")
        axes[0].axis('off')

        # Ground Truth (正解マスク)
        axes[1].imshow(gt_arr, cmap='gray')
        axes[1].set_title("Ground Truth Mask")
        axes[1].axis('off')

        # SAM-CLIP 予測マスク (赤色半透明オーバーレイ)
        axes[2].imshow(orig_img)
        mask_overlay = np.zeros((*pred_arr.shape, 4))
        mask_overlay[pred_arr == 1] = [1, 0, 0, 0.5] # 赤色・透明度50%
        axes[2].imshow(mask_overlay)
        axes[2].set_title(f"SAM-CLIP Output ('{text_prompt}')\nIoU: {iou:.3f} | Prec: {prec:.3f}")
        axes[2].axis('off')

        plt.tight_layout()
        save_path = os.path.join(output_dir, f"result_{idx}_{img_name}")
        plt.savefig(save_path, bbox_inches='tight')
        plt.close(fig)

    num_samples = len(lines)
    mean_iou = total_iou / num_samples
    mean_prec = total_precision / num_samples
    mean_rec = total_recall / num_samples

    # 定量評価レポートの表示
    print("\n================ 評価結果 (Quantitative Report) ================")
    print(f"- Mean IoU       : {mean_iou:.4f}")
    print(f"- Mean Precision : {mean_prec:.4f} (過剰検知抑制の主要指標)")
    print(f"- Mean Recall    : {mean_rec:.4f}")
    print(f"- 可視化結果保存先: {output_dir}")
    print("=================================================================\n")


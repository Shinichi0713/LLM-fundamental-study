"""
改良版マスク選択ロジック
問題: HQ-SAM 2 が「かなり細かくセグメンテーション」= 過剰分割（over-segmentation）
原因: 面積最大だけではSAM 2.1とHQ-SAM 2が「同じ物体」を選んでいる保証がない
解決: 複合的な選択基準 + IoUベースのマッチング
"""

import numpy as np


def compute_iou(mask1, mask2):
    """2つのバイナリマスクのIoU（交差/和）を計算"""
    intersection = np.logical_and(mask1, mask2).sum()
    union = np.logical_or(mask1, mask2).sum()
    return intersection / union if union > 0 else 0.0


def filter_masks(masks, image_shape,
                 min_area_ratio=0.01,    # 画像面積の1%未満を除外
                 max_area_ratio=0.95,     # 画像面積の95%超を除外（背景）
                 min_score=0.80):          # 安定性スコア閾値
    """
    ノイズマスク・背景マスク・低信頼マスクを除外
    """
    img_area = image_shape[0] * image_shape[1]
    min_area = img_area * min_area_ratio
    max_area = img_area * max_area_ratio

    filtered = []
    for m in masks:
        area = m.get("area", 0)
        score = m.get("stability_score", 0)
        if min_area <= area <= max_area and score >= min_score:
            filtered.append(m)
    return filtered


def select_best_mask_v2(masks, image_shape, criterion="combined", reference_mask=None):
    """
    改良版マスク選択

    Parameters:
        masks: マスクリスト
        image_shape: (H, W) 画像サイズ
        criterion: "combined" | "area" | "score" | "iou"
        reference_mask: IoUマッチング用の参照マスク（criterion="iou"時）

    Returns:
        最良マスク（dict）
    """
    if not masks:
        return None

    # ステップ1: フィルタング
    filtered = filter_masks(masks, image_shape)
    if not filtered:
        print("  Warning: フィルタ後にマスクが0件になりました。条件を緩和します。")
        filtered = filter_masks(masks, image_shape, min_area_ratio=0.005, min_score=0.70)
    if not filtered:
        filtered = masks  # 最終 fallback

    print(f"  Filtered: {len(masks)} -> {len(filtered)} masks")

    # ステップ2: 選択基準
    if criterion == "area":
        best = max(filtered, key=lambda m: m.get("area", 0))

    elif criterion == "score":
        best = max(filtered, key=lambda m: m.get("stability_score", 0))

    elif criterion == "iou" and reference_mask is not None:
        # 参照マスクと最も重なるマスクを選択
        best_iou = -1
        best = None
        for m in filtered:
            iou = compute_iou(m["segmentation"], reference_mask)
            if iou > best_iou:
                best_iou = iou
                best = m
        print(f"  Best IoU with reference: {best_iou:.3f}")

    else:  # "combined" - 推奨
        # 面積とスコアの両方を考慮した複合スコア
        img_area = image_shape[0] * image_shape[1]
        best_score = -1
        best = None
        for m in filtered:
            area = m.get("area", 0)
            stability = m.get("stability_score", 0)
            # 面積の正規化（画像に対する比率）
            area_norm = area / img_area
            # 複合スコア: 安定性を重視しつつ、面積も考慮
            # 面積が極端に小いものを減点
            combined = stability * 0.6 + min(area_norm * 5, 0.4)
            if combined > best_score:
                best_score = combined
                best = m
        print(f"  Best combined score: {best_score:.3f}")

    return best



def train_and_eval(num_heads, epochs=3, lr=2e-5):
    print(f"\n==========================================")
    print(f" Starting Experiment: num_heads = {num_heads} ({'Single-Head' if num_heads==1 else 'Multi-Head'})")
    print(f"==========================================")

    model = WinoGrandeClassifier(MODEL_NAME, num_heads=num_heads).to(device)
    optimizer = torch.optim.AdamW(model.parameters(), lr=lr)
    criterion = nn.CrossEntropyLoss()

    for epoch in range(epochs):
        model.train()
        total_loss = 0.0

        for batch in train_loader:
            opt1_ids, opt1_mask, opt2_ids, opt2_mask, labels = batch

            optimizer.zero_grad()
            logits = model(opt1_ids, opt1_mask, opt2_ids, opt2_mask)
            loss = criterion(logits, labels)
            loss.backward()
            optimizer.step()

            total_loss += loss.item()

        # Validation
        model.eval()
        correct = 0
        total = 0
        with torch.no_grad():
            for batch in val_loader:
                opt1_ids, opt1_mask, opt2_ids, opt2_mask, labels = batch
                logits = model(opt1_ids, opt1_mask, opt2_ids, opt2_mask)
                preds = torch.argmax(logits, dim=1)
                correct += (preds == labels).sum().item()
                total += labels.size(0)

        val_acc = correct / total
        avg_train_loss = total_loss / len(train_loader)
        print(f"Epoch {epoch+1}/{epochs} | Train Loss: {avg_train_loss:.4f} | Val Accuracy: {val_acc:.4f}")

    return val_acc



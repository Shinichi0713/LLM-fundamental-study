class WinoGrandeClassifier(nn.Module):
    def __init__(self, base_model_name, num_heads):
        super().__init__()
        # BERT などの Embedding / Encoder 層を利用
        self.encoder = AutoModel.from_pretrained(base_model_name)
        d_model = self.encoder.config.hidden_size

        # 最上層の自己アテンションをカスタム Attention レイヤーに置換して検証する構成
        self.custom_attn = FlexibleAttention(d_model, num_heads=num_heads)
        self.classifier = nn.Linear(d_model, 1)

    def forward_single_option(self, input_ids, attention_mask):
        # Base encoder
        outputs = self.encoder(input_ids=input_ids, attention_mask=attention_mask)
        x = outputs.last_hidden_state

        # カスタムアテンション層の適用
        attn_out = self.custom_attn(x, mask=attention_mask)

        # 文全体の表現として [CLS] トークン (index 0) のベクトルを抽出
        cls_rep = attn_out[:, 0, :]
        logits = self.classifier(cls_rep)
        return logits

    def forward(self, option1_ids, option1_mask, option2_ids, option2_mask):
        # option1 と option2 のスコアをそれぞれ計算
        logits1 = self.forward_single_option(option1_ids, option1_mask)
        logits2 = self.forward_single_option(option2_ids, option2_mask)
        # (Batch, 2) のロジットを結合
        return torch.cat([logits1, logits2], dim=1)



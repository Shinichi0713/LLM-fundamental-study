    model.eval()
    inputs = tokenizer(text, return_tensors="pt", truncation=True, max_length=128).to(device)
    input_ids = inputs["input_ids"]
    attention_mask = inputs["attention_mask"]

    tokens = tokenizer.convert_ids_to_tokens(input_ids[0])

    with torch.no_grad():
        encoder_outputs = model.encoder(input_ids=input_ids, attention_mask=attention_mask)
        x = encoder_outputs.last_hidden_state

        batch_size, seq_len, _ = x.size()
        head_dim = model.custom_attn.head_dim
        num_heads = model.custom_attn.num_heads

        Q = model.custom_attn.q_proj(x).view(batch_size, seq_len, num_heads, head_dim).transpose(1, 2)
        K = model.custom_attn.k_proj(x).view(batch_size, seq_len, num_heads, head_dim).transpose(1, 2)

        scores = torch.matmul(Q, K.transpose(-2, -1)) / math.sqrt(head_dim)
        if attention_mask is not None:
            extended_mask = attention_mask.unsqueeze(1).unsqueeze(2)
            scores = scores.masked_fill(extended_mask == 0, -1e9)

        attn_weights = torch.softmax(scores, dim=-1)

    return attn_weights[0].cpu().numpy(), tokens



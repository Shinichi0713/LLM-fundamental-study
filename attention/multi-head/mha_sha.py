def preprocess_function(examples):
    option1_texts = []
    option2_texts = []
    labels = []

    for sentence, opt1, opt2, answer in zip(examples["sentence"], examples["option1"], examples["option2"], examples["answer"]):
        # 虫食い部分 '_' を各選択肢で置換
        sentence_opt1 = sentence.replace("_", opt1)
        sentence_opt2 = sentence.replace("_", opt2)

        option1_texts.append(sentence_opt1)
        option2_texts.append(sentence_opt2)

        # 正解ラベル ('1' -> 0, '2' -> 1)
        labels.append(0 if answer == "1" else 1)

    enc1 = tokenizer(option1_texts, padding="max_length", truncation=True, max_length=128, return_tensors="pt")
    enc2 = tokenizer(option2_texts, padding="max_length", truncation=True, max_length=128, return_tensors="pt")

    return {
        "opt1_ids": enc1["input_ids"],
        "opt1_mask": enc1["attention_mask"],
        "opt2_ids": enc2["input_ids"],
        "opt2_mask": enc2["attention_mask"],
        "labels": torch.tensor(labels, dtype=torch.long)
    }


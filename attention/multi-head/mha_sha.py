val_data = preprocess_function(raw_dataset["validation"])

# VRAMへ全テンソルを直接移動させてロード時間を大幅高速化
class VRAMDataset(torch.utils.data.Dataset):
    def __init__(self, data_dict):
        self.opt1_ids = data_dict["opt1_ids"].to(device)
        self.opt1_mask = data_dict["opt1_mask"].to(device)
        self.opt2_ids = data_dict["opt2_ids"].to(device)
        self.opt2_mask = data_dict["opt2_mask"].to(device)
        self.labels = data_dict["labels"].to(device)

    def __len__(self):
        return len(self.labels)

    def __getitem__(self, idx):
        return (
            self.opt1_ids[idx], self.opt1_mask[idx],
            self.opt2_ids[idx], self.opt2_mask[idx],
            self.labels[idx]
        )


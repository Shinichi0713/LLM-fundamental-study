import torch.nn.functional as F

def calculate_attention_metrics(model, text, tokenizer):
    model.eval()
    inputs = tokenizer(text, return_tensors="pt", truncation=True, max_length=128).to(device)
    input_ids = inputs["input_ids"]
    attention_mask = inputs["attention_mask"]

    with torch.no_grad():
        encoder_outputs = model.encoder(input_ids=input_ids, attention_mask=attention_mask)
        x = encoder_outputs.last_hidden_state

        batch_size, seq_len, _ = x.size()
        head_dim = model.custom_attn.head_dim
        num_heads = model.custom_attn.num_heads

        Q = model.custom_attn.q_proj(x).view(batch_size, seq_len, num_heads, head_dim).transpose(1, 2)
        K = model.custom_attn.k_proj(x).view(batch_size, seq_len, num_heads, head_dim).transpose(1, 2)

        scores = torch.matmul(Q, K.transpose(-2, -1)) / math.sqrt(head_dim)
        if attention_mask is not None:
            extended_mask = attention_mask.unsqueeze(1).unsqueeze(2)
            scores = scores.masked_fill(extended_mask == 0, -1e9)

        attn = torch.softmax(scores, dim=-1)[0] # (num_heads, seq_len, seq_len)

    # 1. アテンションのエントロピー（集中度）
    # H = - sum(p * log2(p))  (アンダーフロー防止に 1e-9 を加算)
    entropy_per_token = -torch.sum(attn * torch.log2(attn + 1e-9), dim=-1) # (num_heads, seq_len)
    mean_entropy = entropy_per_token.mean(dim=-1) # (num_heads,)

    # 2. ヘッド間コサイン類似度（ヘッド間の多様性: MHAのみ計算可能）
    diversity_matrix = None
    if num_heads > 1:
        # (num_heads, seq_len * seq_len) にフラット化
        flat_attn = attn.view(num_heads, -1)
        # L2正規化
        flat_attn_norm = F.normalize(flat_attn, p=2, dim=1)
        # ヘッド同士のコサイン類似度行列
        diversity_matrix = torch.mm(flat_attn_norm, flat_attn_norm.t()).cpu().numpy()

    # 3. 対角成分（局所集中）率
    seq_range = torch.arange(seq_len, device=device)
    diag_mask = torch.abs(seq_range.unsqueeze(0) - seq_range.unsqueeze(1)) <= 1 # |i-j| <= 1
    diagonal_ratio = (attn * diag_mask.unsqueeze(0)).sum(dim=[-1, -2]) / seq_len # (num_heads,)

    return {
        "num_heads": num_heads,
        "mean_entropy": mean_entropy.cpu().numpy(),
        "diagonal_ratio": diagonal_ratio.cpu().numpy(),
        "diversity_matrix": diversity_matrix
    }


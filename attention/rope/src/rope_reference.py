    print(f"\n[{name}]")
    print(f"  - MLM Loss        : {avg_loss:.4f}")
    print(f"  - Pseudo-PPL      : {pseudo_ppl:.2f}")
    print(f"  - Top-5 Accuracy  : {top5_acc:.2f}%")


def build_mlm_experiment_models(model_name):
    # ① Baseline (標準のMasked LM)
    baseline_model = BertForMaskedLM.from_pretrained(model_name)

    # ② RoPE モデル (BertForMaskedLMベースで構築)
    config = BertConfig.from_pretrained(model_name)
    rope_model = BertForMaskedLM.from_pretrained(model_name)

    # 絶対位置埋め込みの初期化・固定
    nn.init.zeros_(rope_model.bert.embeddings.position_embeddings.weight)
    rope_model.bert.embeddings.position_embeddings.weight.requires_grad = False

    # アテンションブロックの置換
    for i in range(config.num_hidden_layers):
        old_attention = rope_model.bert.encoder.layer[i].attention.self
        new_attention = RoBERTSelfAttention(config)

        # 重みの移植
        new_attention.query.load_state_dict(old_attention.query.state_dict())
        new_attention.key.load_state_dict(old_attention.key.state_dict())
        new_attention.value.load_state_dict(old_attention.value.state_dict())

        # 確実に BertForMaskedLM 内部のモジュールツリーを書き換える
        rope_model.bert.encoder.layer[i].attention.self = new_attention

    return baseline_model, rope_model



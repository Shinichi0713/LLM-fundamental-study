# RoPE ヘルパー関数
# ==============================
def rotate_half(x):
    """
    x: (batch_size, seq_len, num_heads, head_dim)
    """
    x1 = x[..., : x.shape[-1] // 2]
    x2 = x[..., x.shape[-1] // 2 :]
    return torch.cat((-x2, x1), dim=-1)


def apply_rotary_pos_emb(x, cos, sin):
    """
    x: (batch_size, seq_len, num_heads, head_dim)
    cos, sin: (max_seq_len, head_dim)
    """
    # seq_len を取得
    seq_len = x.size(1)

    # cos, sin を seq_len に合わせてスライス
    cos = cos[:seq_len, :]  # (seq_len, head_dim)
    sin = sin[:seq_len, :]  # (seq_len, head_dim)

    # 次元を合わせるために unsqueeze
    cos = cos.unsqueeze(0).unsqueeze(2)  # (1, seq_len, 1, head_dim)
    sin = sin.unsqueeze(0).unsqueeze(2)  # (1, seq_len, 1, head_dim)

    # RoPEの式: q_rot = q * cos + rotate_half(q) * sin
    return (x * cos) + (rotate_half(x) * sin)


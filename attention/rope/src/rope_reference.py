# 2. BERTのSelfAttentionをRoPE対応に拡張
# ==========================================
# transformersの内部クラス「BertSelfAttention」から直接継承します
from transformers.models.bert.modeling_bert import BertSelfAttention

class RoBERTSelfAttention(BertSelfAttention):
    def __init__(self, config):
        super().__init__(config)
        # ヘッド数とヘッドごとの次元数を保持
        self.num_attention_heads = config.num_attention_heads
        self.head_dim = config.hidden_size // config.num_attention_heads
        # RoPEモジュールの初期化
        self.rotary_emb = RotaryEmbedding(dim=self.head_dim)

    def forward(
        self,
        hidden_states,
        attention_mask=None,
        head_mask=None,
        encoder_hidden_states=None,
        encoder_attention_mask=None,
        past_key_value=None,
        output_attentions=False,
        **kwargs,
    ):
        # 1. 完全に線形変換（Linear）を行う
        mixed_query_layer = self.query(hidden_states)
        mixed_key_layer = self.key(hidden_states)
        mixed_value_layer = self.value(hidden_states)

        # 2. 直接テンソルをトランスポーズする
        def shape_for_scores(x):
            new_shape = x.size()[:-1] + (self.num_attention_heads, self.head_dim)
            return x.view(new_shape).permute(0, 2, 1, 3)

        query_layer = shape_for_scores(mixed_query_layer)
        key_layer = shape_for_scores(mixed_key_layer)
        value_layer = shape_for_scores(mixed_value_layer)

        # ----------------------------------------------------
        # 【RoPEの適用ステップ】
        # ----------------------------------------------------
        seq_len = query_layer.shape[2]
        cos, sin = self.rotary_emb(query_layer, seq_len=seq_len)

        # QueryとKeyに回転行列を適用
        query_layer, key_layer = apply_rotary_pos_emb(query_layer, key_layer, cos, sin)
        # ----------------------------------------------------

        # 3. アテンション行列計算（Softmax -> Valueとの積）
        attention_scores = torch.matmul(query_layer, key_layer.transpose(-1, -2))
        attention_scores = attention_scores / math.sqrt(self.head_dim)

        if attention_mask is not None:
            attention_scores = attention_scores + attention_mask

        attention_probs = nn.functional.softmax(attention_scores, dim=-1)
        attention_probs = self.dropout(attention_probs)

        if head_mask is not None:
            attention_probs = attention_probs * head_mask

        context_layer = torch.matmul(attention_probs, value_layer)
        context_layer = context_layer.permute(0, 2, 1, 3).contiguous()
        new_context_layer_shape = context_layer.size()[:-2] + (self.all_head_size,)
        context_layer = context_layer.view(new_context_layer_shape)

        # 【修正】上位層（BertAttention）の unpack (expected 2) に合わせ、常に (output, weights) を返す
        # これにより ValueError: not enough values to unpack を回避します
        return context_layer, attention_probs


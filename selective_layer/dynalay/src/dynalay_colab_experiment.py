@torch.no_grad()
def evaluate(model, loader, record=False):
    model.eval()
    torch.manual_seed(1234)  # randomポリシーの再現性
    T_ = CFG['T_steps']
    N = 0; correct = 0; macs_sum = 0.0; it_sum = 0.0
    hist = np.zeros((T_, N_ACT))
    ce0_l, macs_l = [], []
    for x, y in loader:
        x = x.to(dev, non_blocking=True); y = y.to(dev, non_blocking=True)
        with torch.autocast(device_type=dev.type, dtype=torch.float16, enabled=USE_AMP):
            out = model(x, eps=0.0, greedy=True)
        pred = out['logits'].argmax(1)
        N += y.size(0); correct += (pred == y).sum().item()
        macs_sum += out['macs'].sum().item(); it_sum += out['iters'].sum().item()
        if out['acts'] is not None:
            for t, a in enumerate(out['acts']):
                for k in range(N_ACT):
                    hist[t, k] += (a == k).sum().item()
        if record:
            ce0_l.append(F.cross_entropy(out['logits0'].float(), y, reduction='none').cpu())
            macs_l.append(out['macs'].float().cpu())
    res = dict(acc=100.0 * correct / N, macs=macs_sum / N, iters=it_sum / N, hist=(hist / N).tolist())
    if record:
        ce0 = torch.cat(ce0_l).numpy(); macs = torch.cat(macs_l).numpy()
        rho = spearmanr(ce0, macs)[0] if macs.std() > 0 else 0.0
        res['spearman'] = float(0.0 if np.isnan(rho) else rho)
        # 難易度（初期予測のCE）の5分位ごとの平均MACs（1=易 … 5=難）
        bins = np.digitize(ce0, np.quantile(ce0, [0.2, 0.4, 0.6, 0.8]))
        res['bin_macs'] = [float(macs[bins == b].mean()) if (bins == b).any() else float('nan') for b in range(5)]
    return res

@torch.no_grad()
def time_infer(model, loader, n_batches=20):
    model.eval()
    xs = []
    for i, (x, _) in enumerate(loader):
        xs.append(x.to(dev));
        if i + 1 >= n_batches: break
    def run():
        for x in xs:
            with torch.autocast(device_type=dev.type, dtype=torch.float16, enabled=USE_AMP):
                model(x, eps=0.0, greedy=True)
    for _ in range(2): run()
    if dev.type == 'cuda': torch.cuda.synchronize()
    t0 = time.time(); run()
    if dev.type == 'cuda': torch.cuda.synchronize()
    return 1000.0 * (time.time() - t0) / sum(x.size(0) for x in xs)

def train_run(name, mc, seed):
    set_seed(seed)
    kind, policy = mc['kind'], mc.get('policy', 'none')
    model = DynaNet(kind, policy).to(dev)
    opt = torch.optim.AdamW(model.parameters(), lr=CFG['lr'], weight_decay=CFG['wd'])
    E = CFG['epochs']
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, T_max=E)
    scaler = torch.amp.GradScaler('cuda', enabled=USE_AMP)
    history = []; t_start = time.time()
    for ep in range(E):
        model.train()
        eps = 1.0 if policy == 'random' else max(CFG['eps_min'], 1.0 - ep / max(1, CFG['warmup_epochs']))
        loss_sum, n_b = 0.0, 0
        for x, y in train_loader:
            x = x.to(dev, non_blocking=True); y = y.to(dev, non_blocking=True)
            opt.zero_grad(set_to_none=True)
            with torch.autocast(device_type=dev.type, dtype=torch.float16, enabled=USE_AMP):
                out = model(x, eps=eps, greedy=False)
            loss = F.cross_entropy(out['logits'].float(), y)
            if kind == 'dyna':
                loss = loss + CFG['aux_w'] * F.cross_entropy(out['logits0'].float(), y)
                if policy == 'agent':
                    with torch.no_grad():
                        cf = (out['logits'].argmax(1) == y).float()
                        c0 = (out['logits0'].argmax(1) == y).float()
                        acc_term = cf if mc['reward'] == 'paper' else (cf - c0)
                        R = CFG['alpha'] * acc_term - CFG['beta'] * mc['lam'] * out['penalty']
                        adv = R - R.mean()
                    # L = CE - gamma*R の REINFORCE 版（R は微分不可なので log π で勾配を得る）
                    agent_loss = -(adv * out['logp']).mean() - CFG['ent_coef'] * out['ent']
                    loss = loss + CFG['gamma'] * agent_loss
            scaler.scale(loss).backward()
            scaler.step(opt); scaler.update()
            loss_sum += loss.item(); n_b += 1
        sched.step()
        if (ep + 1) % CFG['eval_every'] == 0 or ep == E - 1:
            r = evaluate(model, test_loader)
            history.append(dict(epoch=ep + 1, loss=loss_sum / n_b, acc=r['acc'], macs=r['macs'], eps=eps))
            print('[%s s%d] ep %2d/%d loss %.3f | test acc %.2f%% | MACs %.1fM | %.0fs' %
                  (name, seed, ep + 1, E, loss_sum / n_b, r['acc'], r['macs'] / 1e6, time.time() - t_start))
    res = evaluate(model, test_loader, record=True)
    res['ms_per_img'] = time_infer(model, test_loader)

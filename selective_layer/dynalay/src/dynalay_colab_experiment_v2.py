@torch.no_grad()
def evaluate(model, loader, record=False):
    model.eval()
    torch.manual_seed(1234)  # randomポリシーの再現性
    T_ = CFG['T_steps']
    N = 0; correct = 0; macs_sum = 0.0; it_sum = 0.0
    hist = np.zeros((T_, N_ACT))
    ce0_l, macs_l = [], []
    for x, y in loader:
        x = x.to(dev, non_blocking=True); y = y.to(dev, non_blocking=True)
        with torch.autocast(device_type=dev.type, dtype=torch.float16, enabled=USE_AMP):
            out = model(x, eps=0.0, greedy=True)
        pred = out['logits'].argmax(1)
        N += y.size(0); correct += (pred == y).sum().item()
        macs_sum += out['macs'].sum().item(); it_sum += out['iters'].sum().item()
        if out['acts'] is not None:
            for t, a in enumerate(out['acts']):
                for k in range(N_ACT):
                    hist[t, k] += (a == k).sum().item()
        if record:
            ce0_l.append(F.cross_entropy(out['logits0'].float(), y, reduction='none').cpu())
            macs_l.append(out['macs'].float().cpu())
    res = dict(acc=100.0 * correct / N, macs=macs_sum / N, iters=it_sum / N, hist=(hist / N).tolist())
    if record:
        ce0 = torch.cat(ce0_l).numpy(); macs = torch.cat(macs_l).numpy()
        rho = spearmanr(ce0, macs)[0] if macs.std() > 0 else 0.0
        res['spearman'] = float(0.0 if np.isnan(rho) else rho)
        bins = np.digitize(ce0, np.quantile(ce0, [0.2, 0.4, 0.6, 0.8]))   # 難易度5分位（初期予測のCE）
        res['bin_macs'] = [float(macs[bins == b].mean()) if (bins == b).any() else float('nan') for b in range(5)]
    return res

@torch.no_grad()
def action_potential(model, loader):
    # 各行動（NOP/L1/L2/L3）を全サンプルに強制適用したときの精度・CE・MACsと、サンプルごとの最良行動（オラクル）
    model.eval()
    cor = [[] for _ in range(N_ACT)]; ces = [[] for _ in range(N_ACT)]; mcs = [0.0] * N_ACT; N = 0
    for x, y in loader:
        x = x.to(dev, non_blocking=True); y = y.to(dev, non_blocking=True)
        N += y.size(0)
        for k in range(N_ACT):
            model.force = k
            with torch.autocast(device_type=dev.type, dtype=torch.float16, enabled=USE_AMP):
                out = model(x, eps=0.0, greedy=True)
            cor[k].append((out['logits'].argmax(1) == y).cpu())
            ces[k].append(F.cross_entropy(out['logits'].float(), y, reduction='none').cpu())
            mcs[k] += out['macs'].sum().item()
    model.force = None
    cor = torch.stack([torch.cat(c) for c in cor]).float(); ces = torch.stack([torch.cat(c) for c in ces])
    return dict(acc=(100 * cor.mean(1)).tolist(), ce=ces.mean(1).tolist(), macs=[m / N for m in mcs],
                oracle_acc=100 * cor.max(0)[0].mean().item(), oracle_ce=ces.min(0)[0].mean().item())

@torch.no_grad()
def time_infer(model, loader, n_batches=20):
    model.eval()
    xs = []
    for i, (x, _) in enumerate(loader):
        xs.append(x.to(dev))
        if i + 1 >= n_batches: break
    def run():
        for x in xs:
            with torch.autocast(device_type=dev.type, dtype=torch.float16, enabled=USE_AMP):
                model(x, eps=0.0, greedy=True)
    for _ in range(2): run()
    if dev.type == 'cuda': torch.cuda.synchronize()
    t0 = time.time(); run()
    if dev.type == 'cuda': torch.cuda.synchronize()
    return 1000.0 * (time.time() - t0) / sum(x.size(0) for x in xs)

def train_run(name, mc, seed):
    set_seed(seed)
    kind, policy = mc['kind'], mc.get('policy', 'none')
    use_agent = (kind == 'dyna' and policy == 'agent')
    P1 = CFG['pretrain_epochs']
    model = DynaNet(kind, policy).to(dev)
    main_params = [p for n_, p in model.named_parameters() if not n_.startswith('agent.')]
    opt = torch.optim.AdamW(main_params, lr=CFG['lr'], weight_decay=CFG['wd'])
    E = CFG['epochs']
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, T_max=E)
    scaler = torch.amp.GradScaler('cuda', enabled=USE_AMP)
    if use_agent:
        opt_a = torch.optim.Adam(model.agent.parameters(), lr=CFG['agent_lr'])
        scaler_a = torch.amp.GradScaler('cuda', enabled=USE_AMP)
        hold_iter = cycle(hold_loader)
    history = []; t_start = time.time()
    for ep in range(E):
        model.train()
        if policy == 'random':
            eps = 1.0
        elif use_agent:
            eps = 1.0 if ep < P1 else max(CFG['eps_min'], CFG['eps_start'] -
                  (CFG['eps_start'] - CFG['eps_min']) * (ep - P1) / max(1, CFG['eps_decay_epochs']))
        else:
            eps = 0.0
        agent_phase = use_agent and ep >= P1
        loss_sum, n_b = 0.0, 0
        for x, y in train_loader:
            x = x.to(dev, non_blocking=True); y = y.to(dev, non_blocking=True)
            # ---- メインモデルの更新（学習データ。dynaでは現在の方策で行動をサンプル）----
            opt.zero_grad(set_to_none=True)
            with torch.autocast(device_type=dev.type, dtype=torch.float16, enabled=USE_AMP):
                out = model(x, eps=eps, greedy=False)
            loss = F.cross_entropy(out['logits'].float(), y)
            if kind == 'dyna':
                loss = loss + CFG['aux_w'] * F.cross_entropy(out['logits0'].float(), y)
            scaler.scale(loss).backward()
            scaler.step(opt); scaler.update()
            loss_sum += loss.item(); n_b += 1
            # ---- エージェントの更新（ホールドアウトで報酬を計算 / メインモデルは更新しない）----
            if agent_phase:
                xh, yh = next(hold_iter)
                xh = xh.to(dev, non_blocking=True); yh = yh.to(dev, non_blocking=True)
                model.agent_only = True
                with torch.no_grad(), torch.autocast(device_type=dev.type, dtype=torch.float16, enabled=USE_AMP):
                    oh = model(xh, eps=eps, greedy=False)
                model.agent_only = False
                with torch.no_grad():
                    lg = oh['logits'].float(); lg0 = oh['logits0'].float()
                    if mc['reward'] == 'paper':      # 論文: R = α·Acc − β·λ·Cost·Consecutive
                        acc_term = (lg.argmax(1) == yh).float()
                    else:                            # 'ce': CE改善量（単位: nat）
                        acc_term = (F.cross_entropy(lg0, yh, reduction='none') -
                                    F.cross_entropy(lg, yh, reduction='none')).clamp(-2.0, 2.0)
                    R = mc['alpha'] * acc_term - mc['beta'] * mc['lam'] * oh['penalty']
                    adv = R - R.mean()
                ent = oh['ent_sum'] / oh['n_alive'].clamp(min=1.0)
                agent_loss = -(adv * oh['logp']).mean() - CFG['ent_coef'] * ent    # REINFORCE（平均ベースライン）
                opt_a.zero_grad(set_to_none=True)
                scaler_a.scale(agent_loss).backward()
                scaler_a.step(opt_a); scaler_a.update()
            if CFG['max_batches'] and n_b >= CFG['max_batches']:
                break
        sched.step()
        if (ep + 1) % CFG['eval_every'] == 0 or ep == E - 1:
            r = evaluate(model, test_loader)
            h0 = r['hist'][0]
            history.append(dict(epoch=ep + 1, loss=loss_sum / n_b, acc=r['acc'], macs=r['macs'], eps=eps))
            act_s = (' | step1 NOP/L1/L2/L3 = %s' % '/'.join('%.0f%%' % (100 * v) for v in h0)) if kind == 'dyna' else ''
            print('[%s s%d] ep %2d/%d loss %.3f | test acc %.2f%% | MACs %.1fM%s | %.0fs' %
                  (name, seed, ep + 1, E, loss_sum / n_b, r['acc'], r['macs'] / 1e6, act_s, time.time() - t_start))
    res = evaluate(model, test_loader, record=True)
    if kind == 'dyna':
        res['potential'] = action_potential(model, test_loader)
    res['ms_per_img'] = time_infer(model, test_loader)
    res['params'] = sum(p.numel() for p in model.parameters())
    res['history'] = history; res['train_time_s'] = time.time() - t_start
    return res, model


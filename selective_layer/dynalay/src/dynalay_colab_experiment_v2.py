def mac_table(ch=CH, res=(32, 16, 8), n_cls=10):
    # 1サンプルあたりのMACs（解析的に計算）
    ins = (3,) + tuple(ch[:-1])
    stage = [ins[i] * ch[i] * 9 * res[i] ** 2 + ch[i] * ch[i] * 9 * res[i] ** 2 for i in range(3)]
    refine = [2 * ch[i] * ch[i] * 9 * (res[i] // 2) ** 2 for i in range(3)]   # FPI 1反復 = conv2枚
    head = ch[-1] * n_cls
    return stage, refine, head

def conv_gn(i, o):
    return nn.Sequential(nn.Conv2d(i, o, 3, padding=1, bias=False), nn.GroupNorm(8, o), nn.ReLU(inplace=True))

def make_stage(i, o):
    return nn.Sequential(conv_gn(i, o), conv_gn(o, o), nn.MaxPool2d(2))

class LipConv(nn.Module):
    # 3x3 conv。固定入力サイズ (c,hw,hw) における「真の作用素ノルム」を power iteration で推定し、
    # 重みを Lipschitz ≤ coeff に正規化する（Gouk et al. 2021 と同様の考え方）
    def __init__(self, c, hw, coeff):
        super().__init__()
        conv = nn.Conv2d(c, c, 3, padding=1)
        self.weight = nn.Parameter(conv.weight.data.clone()); self.bias = nn.Parameter(conv.bias.data.clone())
        self.coeff = coeff
        u = torch.randn(1, c, hw, hw); self.register_buffer('u', u / u.norm())
        self.power_iter(CFG['pi_init'])

    def power_iter(self, n):
        with torch.no_grad():
            W = self.weight.float(); u = self.u
            for _ in range(n):
                v = F.conv2d(u, W, padding=1); v = v / (v.norm() + 1e-12)
                u = F.conv_transpose2d(v, W, padding=1); u = u / (u.norm() + 1e-12)
            self.u.copy_(u)

    def get_w(self):
        with torch.autocast(device_type=self.weight.device.type, enabled=False):
            if self.training:
                self.power_iter(CFG['pi_train'])
            W = self.weight.float()
            sigma = F.conv2d(self.u, W, padding=1).norm()          # u は勾配なし、W には勾配あり
            return W / torch.clamp(sigma / self.coeff, min=1.0), self.bias.float()

class FPIBlock(nn.Module):
    # f(z, x) = x + s * conv2(relu(conv1(z)))  → z についての収縮率は高々 s * coeff^2
    def __init__(self, c, hw, scale):
        super().__init__()
        self.c1 = LipConv(c, hw, CFG['lip_coeff']); self.c2 = LipConv(c, hw, CFG['lip_coeff'])
        self.scale = scale
    def get_w(self):
        return self.c1.get_w(), self.c2.get_w()
    def forward(self, z, x, w=None):
        (W1, b1), (W2, b2) = w if w is not None else self.get_w()
        return x + self.scale * F.conv2d(F.relu(F.conv2d(z, W1, b1, padding=1)), W2, b2, padding=1)

class AgentNet(nn.Module):
    def __init__(self, in_dim, hidden=128):
        super().__init__()
        self.net = nn.Sequential(nn.LayerNorm(in_dim), nn.Linear(in_dim, hidden), nn.ReLU(),
                                 nn.Linear(hidden, N_ACT))
    def forward(self, f):
        return self.net(f)

class DynaNet(nn.Module):
    # kind: 'plain' | 'untied' | 'static' | 'dyna'   policy('dyna'のみ): 'agent' | 'random'
    def __init__(self, kind, policy='none'):
        super().__init__()
        self.kind, self.policy = kind, policy
        self.force = None          # 診断用: 0..3 を指定すると1ステップ目に全サンプルへその行動を強制
        self.agent_only = False    # True: エージェント以外は勾配を作らない（エージェント更新用の高速パス）
        self.stages = nn.ModuleList([make_stage(3, CH[0]), make_stage(CH[0], CH[1]), make_stage(CH[1], CH[2])])
        self.head = nn.Linear(CH[2], 10)
        s = CFG['fpi_scale']
        if kind in ('static', 'dyna'):
            self.refine = nn.ModuleList([FPIBlock(c, hw, s) for c, hw in zip(CH, HW)])
        if kind == 'untied':
            self.refine_u = nn.ModuleList([nn.ModuleList([FPIBlock(c, hw, s) for _ in range(CFG['untied_k'])])
                                           for c, hw in zip(CH, HW)])
        if kind == 'dyna' and policy == 'agent':
            self.agent = AgentNet(sum(CH) + 2 + N_ACT + CFG['T_steps'])
        st, rf, hd = mac_table()
        self.macs_base = float(sum(st) + hd)
        self.macs_ref = [float(r) for r in rf]
        self.macs_down = [float(sum(st[i + 1:]) + hd) for i in range(3)]

    def cls(self, h):
        return self.head(h.mean((2, 3)))

    # FPI: 勾配なしで収束まで反復 → 収束点から1ステップだけ勾配を流す（Jacobian-free）
    def fpi(self, li, x):
        f = self.refine[li]
        w = f.get_w()                      # 正規化済み重みを1回だけ計算（勾配あり）
        with torch.no_grad():
            xd = x.detach(); z = xd
            B = x.size(0)
            active = torch.ones(B, dtype=torch.bool, device=x.device)
            iters = torch.zeros(B, device=x.device)
            for _ in range(CFG['max_iter']):
                fz = f(z, xd, w)
                rel = (fz - z).flatten(1).float().norm(dim=1) / (fz.flatten(1).float().norm(dim=1) + 1e-8)
                z = torch.where(active.view(-1, 1, 1, 1), fz, z)
                iters += active.float()
                active = active & (rel >= CFG['tol'])
                if not active.any():
                    break
        return f(z, x, w), iters + 1.0

    def agent_feats(self, h, logits, prev, t):
        with torch.no_grad():
            B = logits.size(0)
            pooled = [s.float().mean((2, 3)) for s in h]
            p = F.softmax(logits.float(), -1)
            conf = p.max(1, keepdim=True)[0]
            ent = -(p * torch.log(p + 1e-8)).sum(1, keepdim=True) / math.log(p.size(1))
            tt = F.one_hot(torch.full((B,), t, device=logits.device, dtype=torch.long), CFG['T_steps']).float()
            return torch.cat(pooled + [conf, ent, F.one_hot(prev, N_ACT).float(), tt], 1)

    def forward(self, x, eps=0.0, greedy=True):
        B, dev_ = x.size(0), x.device
        zero = torch.zeros(B, device=dev_)
        if self.kind == 'plain':
            h = x
            for s in self.stages: h = s(h)
            lg = self.cls(h)
            return dict(logits=lg, logits0=lg, macs=zero + self.macs_base, iters=zero, logp=zero,
                        penalty=zero, acts=None)
        if self.kind == 'static':
            h = x; it_tot = zero.clone(); macs = zero + self.macs_base
            for li in range(3):
                h = self.stages[li](h)
                h, it = self.fpi(li, h)
                it_tot = it_tot + it; macs = macs + it * self.macs_ref[li]
            lg = self.cls(h)
            return dict(logits=lg, logits0=lg, macs=macs, iters=it_tot, logp=zero, penalty=zero, acts=None)
        if self.kind == 'untied':
            h = x
            for li in range(3):
                h = self.stages[li](h)
                z = h
                for blk in self.refine_u[li]: z = blk(z, h)
                h = z
            lg = self.cls(h)
            K = CFG['untied_k']
            return dict(logits=lg, logits0=lg, macs=zero + self.macs_base + K * sum(self.macs_ref),
                        iters=zero + 3 * K, logp=zero, penalty=zero, acts=None)
        return self.episode(x, eps, greedy)

    # DynaLay: ベース推論 → エージェントが最大T回、層を選んでFPIで精緻化（NOPで停止）
    def episode(self, x, eps, greedy):
        B, dev_ = x.size(0), x.device
        h = []; hh = x
        for s in self.stages:
            hh = s(hh); h.append(hh)
        logits = self.cls(h[2]); logits0 = logits
        base = self.macs_base
        macs = torch.full((B,), base, device=dev_)
        iters_tot = torch.zeros(B, device=dev_); penalty = torch.zeros(B, device=dev_)
        logp = torch.zeros(B, device=dev_)
        ent_sum = torch.zeros((), device=dev_); n_alive = torch.zeros((), device=dev_)
        alive = torch.ones(B, dtype=torch.bool, device=dev_)
        prev = torch.zeros(B, dtype=torch.long, device=dev_)
        consec = torch.zeros(B, device=dev_)
        acts = []
        use_agent = (self.force is None) and (self.policy == 'agent')
        for t in range(CFG['T_steps']):
            ctx = torch.enable_grad() if (use_agent and self.agent_only) else contextlib.nullcontext()
            with ctx:
                if self.force is not None:
                    a = torch.full((B,), self.force if t == 0 else 0, dtype=torch.long, device=dev_)
                    lp = torch.zeros(B, device=dev_); e = torch.zeros(B, device=dev_)
                elif self.policy == 'random':
                    a = torch.randint(0, N_ACT, (B,), device=dev_)
                    lp = torch.full((B,), math.log(1.0 / N_ACT), device=dev_)
                    e = torch.full((B,), math.log(N_ACT), device=dev_)
                else:
                    feats = self.agent_feats(h, logits, prev, t)
                    probs = F.softmax(self.agent(feats).float(), -1)
                    mix = (1 - eps) * probs + eps / N_ACT
                    a = probs.argmax(1) if greedy else torch.multinomial(mix.detach(), 1).squeeze(1)
                    lp = torch.log(mix.gather(1, a[:, None]).squeeze(1) + 1e-8)
                    e = -(probs * torch.log(probs + 1e-8)).sum(1)
                logp = logp + torch.where(alive, lp, torch.zeros_like(lp))
                ent_sum = ent_sum + (e * alive.float()).sum()
                n_alive = n_alive + alive.float().sum()
            a = torch.where(alive, a, torch.zeros_like(a))
            acts.append(torch.where(alive, a, torch.full_like(a, -1)).detach())   # -1: 停止済み
            alive = alive & (a != 0)
            same = (a == prev) & (a != 0)
            consec = torch.where(a == 0, torch.zeros_like(consec),
                                 torch.where(same, consec + 1, torch.ones_like(consec)))
            prev = a
            step_cost = torch.zeros(B, device=dev_)
            for l in (1, 2, 3):
                idx = (a == l).nonzero(as_tuple=True)[0]
                if idx.numel() == 0:
                    continue
                li = l - 1
                z, it = self.fpi(li, h[li][idx])
                hl = h[li].clone(); hl[idx] = z.to(hl.dtype); h[li] = hl
                hh = z
                for m in range(li + 1, 3):
                    hh = self.stages[m](hh)
                    hn = h[m].clone(); hn[idx] = hh.to(hn.dtype); h[m] = hn
                lg = logits.clone(); lg[idx] = self.cls(hh).to(lg.dtype); logits = lg
                step_cost[idx] = it * self.macs_ref[li] + self.macs_down[li]
                iters_tot[idx] += it
            macs = macs + step_cost
            penalty = penalty + step_cost / base * consec    # Cost × ConsecutiveLayerCount
        return dict(logits=logits, logits0=logits0, macs=macs, iters=iters_tot, logp=logp, penalty=penalty,
                    ent_sum=ent_sum, n_alive=n_alive, acts=acts)


@torch.no_grad()
def residual_trace(model, x, li, n=10):
    # FPIの収縮性チェック: 反復ごとの相対残差 ||f(z)-z||/||f(z)||
    model.eval()
    h = x
    for s in model.stages[:li + 1]:
        h = s(h)
    f = model.refine[li]; w = f.get_w(); z = h; res = []
    for _ in range(n):
        fz = f(z, h, w)
        res.append(((fz - z).flatten(1).norm(dim=1) / (fz.flatten(1).norm(dim=1) + 1e-8)).mean().item())
        z = fz
    return res


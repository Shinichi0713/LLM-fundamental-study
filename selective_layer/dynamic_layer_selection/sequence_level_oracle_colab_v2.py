@contextmanager
def skip_layers(model, c):
    # デコーダ層を一時的に差し替える。KV キャッシュの添字ずれを避けるため layer_idx も振り直す。
    dec = model.model.decoder
    orig_layers = dec.layers
    orig_n = model.config.num_hidden_layers
    keep = [i for i, g in enumerate(uniform_pattern(len(orig_layers), c)) if g]
    saved = [(l.self_attn, getattr(l.self_attn, "layer_idx", None)) for l in orig_layers]
    for pos, i in enumerate(keep):
        orig_layers[i].self_attn.layer_idx = pos
    dec.layers = torch.nn.ModuleList([orig_layers[i] for i in keep])
    model.config.num_hidden_layers = len(keep)
    try:
        yield
    finally:
        dec.layers = orig_layers
        model.config.num_hidden_layers = orig_n
        for attn, idx_ in saved:
            attn.layer_idx = idx_


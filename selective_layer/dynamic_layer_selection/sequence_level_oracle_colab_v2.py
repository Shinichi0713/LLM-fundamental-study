"""## 6. （任意）プロンプトから選ぶ学習ルーター

プロンプト特徴量（OPT 中間層の平均プーリング + 長さ）から各モデルの ROUGE-L を Ridge で予測し、
「予測で c=24 より τ 以内に収まる最安モデル」を選びます。5分割クロスバリデーションで評価します。
ルーター自体の計算コスト（プロンプト1回分の前向き計算）は数えていません。
"""

from sklearn.linear_model import Ridge
from sklearn.model_selection import cross_val_predict, KFold
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

FEAT_LAYER, ALPHA = 12, 1000.0

@torch.no_grad()
def extract_features():
    path = f"{CFG['out_dir']}/feats_l{FEAT_LAYER}_n{len(prompts)}.npy"
    if os.path.exists(path): return np.load(path)
    # LoRA 注入後でも「素のモデル」の特徴量になるよう、アダプタを無効化して計算
    ctx = peft_model.disable_adapter() if "peft_model" in globals() else nullcontext()
    feats = [None] * len(prompts); order = np.argsort([len(p) for p in prompts])
    with ctx:
        for s in tqdm(range(0, len(order), CFG["batch_size"]), desc="features"):
            b = order[s:s + CFG["batch_size"]]
            enc = tok([prompts[i] for i in b], return_tensors="pt", padding=True, truncation=True,
                      max_length=CFG["max_prompt_tokens"]).to(device)
            hs = model(**enc, output_hidden_states=True).hidden_states[FEAT_LAYER]
            m = enc["attention_mask"].unsqueeze(-1).to(hs.dtype)
            pooled = ((hs * m).sum(1) / m.sum(1)).float().cpu().numpy()
            lens = enc["attention_mask"].sum(1).float().cpu().numpy()
            for k, i in enumerate(b): feats[i] = np.concatenate([pooled[k], [math.log(lens[k])]])
    X = np.stack(feats); np.save(path, X); return X

def analyze_router(R, X, label, plot=True):
    n = len(R); costs_arr = np.array(costs); idx_n = np.arange(n); mean_R = R.mean(0)
    cv = KFold(5, shuffle=True, random_state=CFG["seed"])
    Rhat = np.column_stack([
        cross_val_predict(make_pipeline(StandardScaler(), Ridge(alpha=ALPHA)), X, R[:, j], cv=cv)
        for j in range(len(costs))])
    corr = [round(float(np.corrcoef(Rhat[:, j], R[:, j])[0, 1]), 3) for j in range(len(costs))]
    taus = np.linspace(-0.05, 0.4, 46)
    cs, sc, mx = [], [], []
    for tau in taus:
        ok = Rhat >= (Rhat[:, [-1]] - tau); ok[:, -1] = True
        sel = ok.argmax(1)                         # costs は昇順なので最安のモデル
        sh = np.bincount(sel, minlength=len(costs)) / n
        cs.append(costs_arr[sel].mean()); sc.append(R[idx_n, sel].mean()); mx.append(sh @ mean_R)
    res = dict(label=label, cost=np.array(cs), score=np.array(sc), mix=np.array(mx), corr=corr)
    print(f"[{label}] 予測と実測の相関:", corr)
    if plot:
        o = analyze_oracle(R, label, plot=False)
        plt.figure(figsize=(7, 5))
        plt.plot(o["betas"], o["orc"], lw=2, label="oracle")
        plt.plot(cs, sc, "o-", ms=3, label="learned router (CV)")
        plt.plot(cs, mx, "--", label="random mix (router と同じ比率)")
        plt.plot(costs, mean_R, "k^", ms=9, label="static ULS")
        plt.xlabel("average cost (layers)"); plt.ylabel("mean ROUGE-L"); plt.title(label)
        plt.grid(alpha=.3); plt.legend(); plt.show()
    return res


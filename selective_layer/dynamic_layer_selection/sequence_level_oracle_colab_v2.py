"""## 4. 分析用の関数

- **oracle**: 平均コスト ≤ β の制約下で平均 ROUGE-L を最大化（多選択ナップサック, DP）
- **greedy oracle**: 各系列で c ≤ β のモデルのうち最良を選ぶだけ（予算の融通なし）。sampling advantage の近似（論文 A.5.1）
- **random mix**: oracle と同じ選択比率でランダムに割り当てた場合の期待値
"""

def solve_oracle(R, costs, betas):
    # 多選択ナップサック（各系列にちょうど1モデル）を DP で解く。
    n, k = R.shape
    g = reduce(gcd, costs); u = [c // g for c in costs]
    Wmax = n * max(u)
    prev = np.zeros(Wmax + 1)                      # 「コスト w 以下」の意味
    choices = np.zeros((n, Wmax + 1), dtype=np.int8)
    for i in range(n):
        new = np.full(Wmax + 1, -np.inf); ch = np.zeros(Wmax + 1, dtype=np.int8)
        for j in range(k):
            cand = np.full(Wmax + 1, -np.inf)
            cand[u[j]:] = prev[:Wmax + 1 - u[j]] + R[i, j]
            m = cand > new; new[m] = cand[m]; ch[m] = j
        prev, choices[i] = new, ch
    out = []
    for b in betas:
        W = min(int(np.floor(b * n / g + 1e-9)), Wmax)
        if not np.isfinite(prev[W]): out.append(None); continue
        a = np.zeros(n, dtype=int); w = W
        for i in range(n - 1, -1, -1):
            j = choices[i, w]; a[i] = j; w -= u[j]
        out.append(a)
    return out

def analyze_oracle(R, label, plot=True):
    n = len(R); costs_arr = np.array(costs); idx_n = np.arange(n); mean_R = R.mean(0)
    betas = np.arange(4, 24.01, 0.5)
    assigns = solve_oracle(R, costs, betas)
    orc_score = np.array([R[idx_n, a].mean() for a in assigns])
    shares = np.array([np.bincount(a, minlength=len(costs)) / n for a in assigns])
    mix_score = shares @ mean_R
    greedy = {}
    for b in costs:
        allowed = [j for j, c in enumerate(costs) if c <= b]
        sel = np.array(allowed)[R[:, allowed].argmax(1)]
        greedy[b] = (costs_arr[sel].mean(), R[idx_n, sel].mean())
    full = mean_R[-1]; hit = np.where(orc_score >= full)[0]
    res = dict(label=label, betas=betas, orc=orc_score, shares=shares, mix=mix_score, greedy=greedy,
               mean_R=mean_R, hit_beta=(betas[hit[0]] if len(hit) else None),
               hit_share=(shares[hit[0]] if len(hit) else None))
    if plot:
        fig, ax = plt.subplots(1, 2, figsize=(14, 4.8))
        a0 = ax[0]
        a0.plot(betas, orc_score, lw=2, label="oracle (knapsack)")
        a0.plot(betas, mix_score, "--", label="random mix (same proportions)")
        a0.plot(*zip(*[greedy[b] for b in costs]), "s-", ms=7, label="greedy oracle (β=4,8,12,24)")
        a0.plot(costs, mean_R, "k^", ms=9, label="static ULS models")
        a0.axhline(full, color="gray", ls=":", label="full model")
        a0.set_xlabel("average cost β (layers)"); a0.set_ylabel("mean ROUGE-L"); a0.legend(); a0.grid(alpha=.3)
        a0.set_title(f"ROUGE-L vs budget [{label}]")
        a1 = ax[1]
        a1.stackplot(betas, shares.T * 100, labels=[f"c={c}" for c in costs], alpha=.85)
        a1.set_xlabel("average cost β (layers)"); a1.set_ylabel("selected by oracle (%)")
        a1.legend(loc="lower right"); a1.set_title(f"model selection share [{label}]"); a1.set_xlim(4, 24)
        plt.tight_layout(); plt.show()
    if plot:
        print(f"[{label}] フルモデル {full:.3f}")
        if res["hit_beta"] is not None:
            h = hit[0]
            print(f"  オラクルがフルに並ぶ最小の β ≈ {betas[h]:.1f} 層 ({betas[h]/24*100:.1f}%)",
                  {f"c={c}": f"{shares[h, j]*100:.1f}%" for j, c in enumerate(costs)},
                  f"/ 同混合比ランダム期待 {mix_score[h]:.3f}")
        else:
            print("  オラクルがフルに届かず")
        b8 = list(betas).index(8.0)
        print(f"  β=8: oracle {orc_score[b8]:.3f} / greedy {greedy[8][1]:.3f} / random mix {mix_score[b8]:.3f} / 静的 c=8 {mean_R[1]:.3f}")
    return res


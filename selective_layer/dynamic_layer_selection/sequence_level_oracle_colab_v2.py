def uniform_pattern(L, c):
    # 論文 式(2): U(l,c) = 1((sum_{k<l} U(k,c)) <= (l-1)*c/L), U(1,c)=1
    U = [1]
    for l in range(2, L + 1):
        U.append(1 if sum(U) <= (l - 1) * c / L + 1e-9 else 0)
    return U


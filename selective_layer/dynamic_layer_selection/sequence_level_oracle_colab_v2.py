def collate(batch):
    m = max(len(x) for x, _ in batch)
    ids = torch.full((len(batch), m), tok.pad_token_id, dtype=torch.long)
    lab = torch.full((len(batch), m), -100, dtype=torch.long)
    att = torch.zeros((len(batch), m), dtype=torch.long)
    for k, (x, y) in enumerate(batch):
        ids[k, :len(x)] = torch.tensor(x); lab[k, :len(y)] = torch.tensor(y); att[k, :len(x)] = 1
    return ids.to(device), att.to(device), lab.to(device)

def train_adapter(c):
    name = f"c{c}"
    path = f"{CFG['out_dir']}/lora_{name}_n{len(train_data)}_e{CFG['ft_epochs']}.pt"
    peft_model.set_adapter(name)
    params = {n_: p for n_, p in peft_model.named_parameters() if "lora_" in n_ and f".{name}." in n_}
    if os.path.exists(path):
        peft_model.load_state_dict(torch.load(path, map_location=device), strict=False)
        print(f"{name}: loaded from cache"); return
    for n_, p in peft_model.named_parameters():
        p.requires_grad = n_ in params
    for p in params.values():
        p.data = p.data.float()
    opt = torch.optim.AdamW(list(params.values()), lr=CFG["ft_lr"], weight_decay=0.0)
    bs, accum = CFG["ft_batch"], CFG["ft_accum"]
    steps = CFG["ft_epochs"] * (len(train_data) // bs) // accum
    sched = get_linear_schedule_with_warmup(opt, max(1, int(0.03 * steps)), steps)
    scaler = torch.cuda.amp.GradScaler()
    peft_model.train(); t0 = time.time(); run, k = 0.0, 0
    rs = np.random.RandomState(CFG["seed"])
    with skip_layers(base, c):                                  # スキップ状態のまま学習
        for ep in range(CFG["ft_epochs"]):
            order = rs.permutation(len(train_data))
            for s in range(0, len(order) - bs + 1, bs):
                ids, att, lab = collate([train_data[i] for i in order[s:s + bs]])
                with torch.autocast("cuda", dtype=torch.float16):
                    loss = peft_model(input_ids=ids, attention_mask=att, labels=lab, use_cache=False).loss / accum
                scaler.scale(loss).backward(); run += loss.item() * accum; k += 1
                if k % accum == 0:
                    scaler.unscale_(opt); torch.nn.utils.clip_grad_norm_(list(params.values()), 1.0)
                    scaler.step(opt); scaler.update(); opt.zero_grad(set_to_none=True); sched.step()
                    if (k // accum) % 25 == 0:
                        print(f"  {name} step {k//accum}/{steps}  loss {run/(25*accum):.3f}  {time.time()-t0:.0f}s"); run = 0.0
    peft_model.eval()
    torch.save({n_: p.detach().cpu() for n_, p in params.items()}, path)
    print(f"{name}: done in {time.time()-t0:.0f}s")

for c in costs:
    train_adapter(c)


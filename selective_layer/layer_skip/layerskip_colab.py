"""## 8. Self-Speculative Decoding（`assistant_early_exit`）

前半 `k` 層で下書きを生成し、全層で一括検証します。貪欲デコードなので、**出力は通常の生成と一致するはず**です。

> 注意: 0.5B 程度の小型モデルでは、GPU カーネル起動のオーバーヘッドが支配的で、速度向上が出ない（むしろ遅くなる）ことがあります。また、少量データの学習では浅い層の予測精度が十分に上がらず、下書きの受理率も低くなります。ここでは「仕組みが動くこと」の確認が主目的です。大きな高速化を見るには 8 の公式チェックポイント（1B 以上）を使ってください。
"""

prompt = "The history of the Roman Empire began when"
inputs = tok(prompt, return_tensors="pt").to(device)
N_NEW = 128

def bench(**gen_kwargs):
    kw = dict(max_new_tokens=N_NEW, do_sample=False, pad_token_id=tok.pad_token_id)
    model.generate(**inputs, **{**kw, "max_new_tokens": 8}, **gen_kwargs)   # ウォームアップ
    torch.cuda.synchronize(); t = time.time()
    out = model.generate(**inputs, **kw, **gen_kwargs)
    torch.cuda.synchronize(); dt = time.time() - t
    n = out.shape[1] - inputs["input_ids"].shape[1]
    return out, n / dt

base_out, base_tps = bench()
rows = [{"mode": "通常デコード", "exit_layer": "-", "tokens/s": round(base_tps, 1), "出力一致": True}]

for k in sorted({L // 4, L // 3, L // 2}):
    try:
        out, tps = bench(assistant_early_exit=k)
        same = torch.equal(out[0][: base_out.shape[1]], base_out[0][: out.shape[1]])
        rows.append({"mode": "self-speculative", "exit_layer": k, "tokens/s": round(tps, 1), "出力一致": same})
    except Exception as e:
        rows.append({"mode": "self-speculative", "exit_layer": k, "tokens/s": None, "出力一致": f"error: {type(e).__name__}: {e}"[:80]})

display(pd.DataFrame(rows))
print(tok.decode(base_out[0], skip_special_tokens=True))


DROPOUT_WARMUP_FRAC = 0.2   # 学習の最初の 20% でドロップ率を 0 → P_MAX に増やす（時間カリキュラム）
E_SCALE = 0.5               # 中間層の Early Exit Loss の最大重み（最終層は 1.0）

# ---- 保存 ----

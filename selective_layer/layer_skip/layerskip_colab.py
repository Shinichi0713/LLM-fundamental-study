"""## 次の一手
- `MAX_STEPS` を増やす、データ量を増やす（日本語など自分の用途のデータに差し替え）
- `P_MAX` / `E_SCALE` / `EXIT_LAYERS` を変えて、浅い層の精度と最終層の精度のトレードオフを確認
- ドロップをサンプル単位にする、ドロップ率を指数カーブにする、層ごとの Early Exit のカリキュラムを入れる（論文の設定に近づける）
- 7B 級へ適用する場合は LoRA / QLoRA とより大きな GPU が必要
"""

base = AutoModelForCausalLM.from_pretrained(MODEL_NAME, torch_dtype=INFER_DTYPE).to(device).eval()

prompts = [
    "The history of the Roman Empire began when",
    "Albert Einstein was born in",
    "Monday, Tuesday, Wednesday,",
    "1, 2, 3, 4, 5, 6, 7, 8,",
    "def add(a, b):\n    return a + b\n\ndef sub(a, b):\n    return",
]
CHECK_LAYERS = [L // 4, L // 2, (3 * L) // 4, L]

@torch.no_grad()
def exit_generate(m, prompt, exit_layer, n_new=15):
    Lm = len(m.model.layers)
    ids = tok(prompt, return_tensors="pt").input_ids.to(device)
    buf = {}
    h = None
    if exit_layer < Lm:
        h = m.model.layers[exit_layer - 1].register_forward_hook(
            lambda mod, i, o: buf.__setitem__("h", o[0] if isinstance(o, tuple) else o))
    for _ in range(n_new):
        out = m.model(input_ids=ids, use_cache=False)
        hs = out.last_hidden_state if exit_layer == Lm else m.model.norm(buf["h"])
        nxt = m.lm_head(hs[:, -1]).argmax(-1, keepdim=True)
        ids = torch.cat([ids, nxt], dim=1)
    if h: h.remove()
    return tok.decode(ids[0, -n_new:])

@torch.no_grad()
def agreement(m, prompt, layers_, n_new=64):
    Lm = len(m.model.layers)
    inp = tok(prompt, return_tensors="pt").to(device)
    full = m.generate(**inp, max_new_tokens=n_new, do_sample=False, pad_token_id=tok.pad_token_id)
    cap = {}
    hooks = [m.model.layers[l - 1].register_forward_hook(
                lambda mod, i, o, l=l: cap.__setitem__(l, o[0] if isinstance(o, tuple) else o))
             for l in layers_ if l < Lm]
    out = m.model(input_ids=full, use_cache=False)
    s = inp["input_ids"].shape[1] - 1                       # 生成部分の予測位置のみ評価
    final = m.lm_head(out.last_hidden_state)[:, s:-1].argmax(-1)
    res = {}
    for l in layers_:
        h = out.last_hidden_state if l == Lm else m.model.norm(cap[l])
        res[l] = (m.lm_head(h)[:, s:-1].argmax(-1) == final).float().mean().item()
    for x in hooks: x.remove()
    return res

# 1) 中間層で止めた生成結果
for p in prompts[:2]:
    print("PROMPT:", repr(p))
    for name, m in [("before", base), ("after ", model)]:
        for l in CHECK_LAYERS:
            print(f"  {name} L{l:>2}: {exit_generate(m, p, l)!r}")

# 2) 最終層との一致率（下書き受理率の目安）
rows = []
for p in prompts:
    for name, m in [("before", base), ("after", model)]:
        a = agreement(m, p, CHECK_LAYERS)
        rows.append({"prompt": p[:28].replace("\n", " "), "model": name, **{f"L{l}": round(v, 2) for l, v in a.items()}})
display(pd.DataFrame(rows))


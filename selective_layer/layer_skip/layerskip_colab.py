plt.plot(df["layer"], df["ppl_before"], "o-", label="before")
plt.plot(df["layer"], df["ppl_after"], "o-", label="after LayerSkip training")
plt.yscale("log"); plt.xlabel("exit layer"); plt.ylabel("perplexity (log)")
plt.legend(); plt.grid(alpha=.3); plt.show()

"""学習前は中間層から直接予測すると perplexity が極端に大きく、学習後に浅い層でも大きく改善していれば成功です。最終層の perplexity が大きく悪化していないかも確認してください。

## 7. 保存
"""


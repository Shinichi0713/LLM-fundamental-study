# === HTMLで色を付けるユーティリティ ===
def color_text(text, color):
    return f"<span style='color:{color}; font-weight:bold'>{text}</span>"


# === メイン可視化関数（文章ごとに改行対応） ===
def visualize_mlm_predictions(model, dataloader, tokenizer, device):
    model.eval()

    batch = next(iter(dataloader))
    input_ids = batch["input_ids"].to(device)
    labels = batch["labels"].to(device)

    ids = input_ids[0].unsqueeze(0)

    with torch.no_grad():
        logits, _ = model(ids, global_mask=None, labels=None)

    pred_ids = torch.argmax(logits, dim=-1)[0].cpu().tolist()
    orig_ids = ids[0].cpu().tolist()
    label_ids = labels[0].cpu().tolist()

    html_output = ""

    # === 文区切り候補 ===
    sentence_end_tokens = ["。", "!", "！", "？", "?"]
    sep_token_id = tokenizer.sep_token_id

    for orig, pred, lab in zip(orig_ids, pred_ids, label_ids):

        # 特殊トークン処理
        if orig in tokenizer.all_special_ids:
            tok = tokenizer.decode([orig])
            html_output += color_text(tok, "gray") + " "

            # [SEP] などでは改行
            if orig == sep_token_id:
                html_output += "<br><br>"
            continue

        orig_token = tokenizer.decode([orig])
        pred_token = tokenizer.decode([pred])

        # === MASK 部分を色付け ===
        if lab != -100:
            html_output += (
                color_text(f"[MASK→{pred_token}]", "red")
                + color_text(f"({orig_token})", "blue")
                + " "
            )
        else:
            html_output += orig_token + " "

        # === 文の最後なら改行する ===
        if orig_token in sentence_end_tokens:
            html_output += "<br><br>"

    display(HTML("<div style='font-size:18px; line-height:1.8'>" + html_output + "</div>"))


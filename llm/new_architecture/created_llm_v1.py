def predict_mask(text, model, tokenizer, device, top_k=5): # (1) deviceを追加
    model.eval()
    model.to(device) # (2) モデルを指定デバイスに移動

    # テキストをトークン化
    inputs = tokenizer(text, return_tensors="pt")

    # (3) 入力テンソルを指定デバイスに移動
    input_ids = inputs["input_ids"].to(device)

    # マスクの位置を探す
    mask_token_id = tokenizer.mask_token_id
    # (4) torch.whereの出力（mask_indices）もinput_idsと同じデバイス上にあるはずです。
    mask_indices = torch.where(input_ids == mask_token_id)[1]

    if len(mask_indices) == 0:
        print("MASKトークンが見つかりませんでした。")
        return

    with torch.no_grad():
        # modelがGPU上にあり、input_idsもGPU上にあることを確認
        logits, _ = model(input_ids)
        # logitsもGPU上にあります

    # マスク位置の予測を取得
    for mask_idx in mask_indices:
        # mask_logitsはGPU上にあります
        mask_logits = logits[0, mask_idx, :]
        # top_k_idsもGPU上にあります
        top_k_ids = torch.topk(mask_logits, top_k).indices

        print(f"\nOriginal Text: {text}")
        # item() でCPUに取り出す
        print(f"Mask Position: {mask_idx.item()}")
        print("Predictions:")
        for rank, token_id in enumerate(top_k_ids):
            # token_idをCPUに移動してからdecodeに渡す（これは通常不要ですが、安全のため）
            token = tokenizer.decode([token_id.item()])
            print(f"  {rank+1}. {token}")



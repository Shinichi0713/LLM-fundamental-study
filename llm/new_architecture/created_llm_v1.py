class MockTokenizer:
    def __init__(self):
        self.vocab = {
            1: "[CLS]", 2: "[MASK]", 3: "[SEP]", 4: "[PAD]",
            5: "学習", 8: "モデル", 12: "デコード", 20: "プロセス",
            24: "成功", 25: "完了", 40: "結果", 45: "確認", 46: "分析",
            100: "処理", 110: "コード"
        }
        self.special_tokens = {"[CLS]", "[MASK]", "[SEP]", "[PAD]"}
        self.pad_token_id = 4

    def decode(self, token_ids, skip_special_tokens=False):
        tokens = []
        for tid in token_ids:
            if tid == -100 or tid == self.pad_token_id:
                continue
            token = self.vocab.get(tid, f"[UNK_{tid}]")
            if skip_special_tokens and token in self.special_tokens:
                continue
            tokens.append(token)
        return " ".join(tokens)


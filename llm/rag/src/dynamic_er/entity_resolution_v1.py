def resolve_query_entities(query: str, entity_kb: dict, entity_history: dict,
                           alpha: float = 0.5, threshold: float = 0.5):
    """
    クエリ中のメンションをKBエンティティに解決（TempCCA的アプローチ）

    Parameters:
        query: ユーザーの質問文
        entity_kb: {entity_id: 正規説明文}
        entity_history: {entity_id: [過去に使われたメンションリスト]}
        alpha: 静的表現 vs 動的表現のバランス（0~1）
        threshold: リンク確定の閾値

    Returns:
        resolved_query: 名寄せ後の正規化クエリ
        best_entity: 最も近いエンティティID
        confidence: 信頼度スコア
    """
    query_vec = sbert.encode([query])

    best_match = None
    best_score = -1

    print(f"\n🔍 クエリ: '{query}'")
    print("--- Affinityスコア ---")

    for eid, desc in entity_kb.items():
        # 静的エンティティ表現（KBの説明文）
        static_vec = sbert.encode([desc])

        # 継続的適応: 過去メンションの平均を混ぜる
        if eid in entity_history and len(entity_history[eid]) > 0:
            hist_vecs = sbert.encode(entity_history[eid])
            dynamic_vec = alpha * static_vec + (1 - alpha) * np.mean(hist_vecs, axis=0)
        else:
            dynamic_vec = static_vec

        # Affinity計算（コサイン類似度）
        sim = cosine_similarity(query_vec, dynamic_vec.reshape(1, -1))[0][0]

        entity_name = desc.split("は")[0] if "は" in desc else desc[:20]
        print(f"  φ({entity_name}, query) = {sim:.4f}")

        if sim > best_score:
            best_score = sim
            best_match = eid

    # 閾値チェック
    if best_score < threshold:
        print(f"⚠️ 閾値({threshold})を下回るため、名寄せをスキップ")
        return query, None, best_score

    # 正規化（クエリ内の略称を正規名に置換）
    canonical_name = entity_kb[best_match].split("は")[0]
    # 簡易的な置換: クエリ中の単語を正規名に置換（実際はもっと賢く必要）
    resolved_query = query  # ここでは単純化

    print(f"✅ 名寄せ結果: '{query}' → {best_match}({canonical_name}), 信頼度={best_score:.3f}")

    return resolved_query, best_match, best_score


def retrieve_with_resolution(query: str, index: VectorStoreIndex,
                             entity_kb: dict, entity_history: dict,
                             alpha: float = 0.5, top_k: int = 3):
    """
    名寄せを挟んでからRetrieverを実行するRAGパイプライン
    """
    # Step 1: 名寄せ
    resolved_query, entity_id, confidence = resolve_query_entities(
        query, entity_kb, entity_history, alpha=alpha
    )

    # Step 2: 名寄せ成功時は正規名で検索
    if entity_id:
        canonical_name = entity_kb[entity_id].split("は")[0]
        # クエリ中の略称らしき部分を正規名に置換して検索
        search_query = canonical_name + " " + query
        print(f"🔎 検索クエリ: '{search_query}'")
    else:
        search_query = query
        print(f"🔎 検索クエリ（名寄せなし）: '{search_query}'")

    # Step 3: Retriever実行
    retriever = VectorIndexRetriever(index, similarity_top_k=top_k)
    nodes = retriever.retrieve(search_query)

    return nodes, entity_id, confidence



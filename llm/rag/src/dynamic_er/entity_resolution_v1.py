def extract_mention_candidates(query: str) -> list:
    """
    クエリから「固有名詞っぽい部分」を抽出
    簡易版：助詞「の」「は」「を」などで分割して先頭の名詞句を抽出
    """
    # 「の」「は」「が」「を」「に」「で」で分割
    parts = re.split(r'[のはがをにで]', query)
    candidates = [p.strip() for p in parts if len(p.strip()) >= 2]
    return candidates


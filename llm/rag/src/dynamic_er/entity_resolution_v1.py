def retrieve_with_backward_resolution(query: str, index: VectorStoreIndex,
                                      entity_kb: dict, entity_history: dict,
                                      alpha: float = 0.3, threshold: float = 0.4,
                                      top_k: int = 5):
    """
    2段階推定：
    Step 1: 通常のRetrieverで上位文書を取得（名寄せなし）
    Step 2: 取得した文書の内容から、どのエンティティに近いか再判定
    Step 3: 再判定結果でクエリを正規化して再検索 or Generatorに渡す
    """
    print(f"\nPoC用クエリ: '{query}'")

    # Step 1: 名寄せなしでRetriever実行（広く検索）
    retriever = VectorIndexRetriever(index, similarity_top_k=top_k)
    initial_nodes = retriever.retrieve(query)

    print("--- 初回検索結果 ---")
    for i, node in enumerate(initial_nodes[:3], 1):
        print(f"  {i}. {node.text[:40]}... (出典: {node.metadata['source']})")

    # Step 2: 検索結果の文書とエンティティのAffinityを計算
    print("--- 検索結果からの逆推定 ---")

    best_match = None
    best_score = -1

    # 検索結果上位3件のテキストを結合して1つの文脈ベクトルに
    context_text = " ".join([n.text for n in initial_nodes[:3]])
    context_vec = sbert.encode([context_text])

    for eid, desc in entity_kb.items():
        static_vec = sbert.encode([desc])

        # 継続的適応
        if eid in entity_history and len(entity_history[eid]) > 0:
            hist_vecs = sbert.encode(entity_history[eid])
            dynamic_vec = alpha * static_vec + (1 - alpha) * np.mean(hist_vecs, axis=0)
        else:
            dynamic_vec = static_vec

        # 文脈とエンティティの類似度
        sim = cosine_similarity(context_vec, dynamic_vec.reshape(1, -1))[0][0]
        entity_name = desc.split("は")[0] if "は" in desc else desc[:20]
        print(f"  文脈 vs {entity_name} = {sim:.4f}")

        if sim > best_score:
            best_score = sim
            best_match = eid

    # Step 3: 閾値チェック
    if best_score < threshold:
        print(f"⚠️ 逆推定スコア{best_score:.3f}が閾値を下回るため、正規化をスキップ")
        return initial_nodes, None, best_score

    # 正規化して再検索 or そのまま返す
    canonical_name = entity_kb[best_match].split("は")[0]
    resolved_query = query  # 必要に応じて置換

    print(f"オレオレ逆推定: 検索文脈 → {best_match}({canonical_name}), 信頼度={best_score:.3f}")

    # 再検索（正規名を追加）
    retriever2 = VectorIndexRetriever(index, similarity_top_k=top_k)
    final_nodes = retriever2.retrieve(f"{canonical_name} {query}")

    return final_nodes, best_match, best_score



# =========================================
# 1. サンプル文書
# =========================================

documents = [
    "山田部長はネコプロジェクトの責任者である。",
    "ネコプロジェクトはCRM基盤に影響する。",
    "山田部長は営業企画部に所属している。",
    "営業企画部は顧客対応AIの導入を推進している。",
    "CRM基盤は顧客情報を管理する社内システムである。"
]

question = "山田部長が責任を持つプロジェクトは、どのシステムに影響しますか？"


# =========================================
# 2. 通常RAG風：単純なキーワード検索
# =========================================

def simple_keyword_search(question, documents):
    results = []
    for doc in documents:
        score = 0
        for word in ["山田部長", "責任", "プロジェクト", "システム", "影響"]:
            if word in question and word in doc:
                score += 1
        if score > 0:
            results.append((score, doc))
    return sorted(results, reverse=True)


print("=== 通常RAG風の検索結果 ===")
for score, doc in simple_keyword_search(question, documents):
    print(f"score={score}: {doc}")

# =========================================
# 3. オントロジー定義
# =========================================
# これは「どんな種類のものがあり、どう関係できるか」の設計図

ontology = {
    "entity_types": ["Person", "Department", "Project", "System"],
    "relations": [
        "responsible_for",   # Person -> Project
        "affects",           # Project -> System
        "belongs_to",        # Person -> Department
        "promotes"           # Department -> Project/System
    ]
}

print("=== オントロジー ===")
print(ontology)

# =========================================
# 4. 文書から抽出済みと仮定したナレッジグラフ
# =========================================
# 実務ではここをNER/LLM/ルールで自動抽出する

triples = [
    ("山田部長", "responsible_for", "ネコプロジェクト"),
    ("ネコプロジェクト", "affects", "CRM基盤"),
    ("山田部長", "belongs_to", "営業企画部"),
    ("営業企画部", "promotes", "顧客対応AI"),
    ("CRM基盤", "type", "System"),
    ("ネコプロジェクト", "type", "Project"),
    ("山田部長", "type", "Person"),
    ("営業企画部", "type", "Department")
]

print("=== ナレッジグラフの三つ組 ===")
for s, r, o in triples:
    print(f"{s} --{r}--> {o}")

# =========================================
# 5. GraphRAG風：関係をたどって答えを導出する
# =========================================

def find_objects(subject, relation, triples):
    return [o for s, r, o in triples if s == subject and r == relation]

def graph_reasoning_answer(person_name):
    # 1. 人物が責任を持つプロジェクトを探す
    projects = find_objects(person_name, "responsible_for", triples)

    answers = []

    # 2. そのプロジェクトが影響するシステムを探す
    for project in projects:
        systems = find_objects(project, "affects", triples)
        for system in systems:
            answers.append({
                "person": person_name,
                "project": project,
                "system": system,
                "reasoning_path": f"{person_name} --responsible_for--> {project} --affects--> {system}"
            })

    return answers


print("=== オントロジー + GraphRAG風の導出結果 ===")
answers = graph_reasoning_answer("山田部長")

for ans in answers:
    print("答え:", ans["system"])
    print("導出経路:", ans["reasoning_path"])


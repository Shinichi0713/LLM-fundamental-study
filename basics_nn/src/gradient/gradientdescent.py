import numpy as np
import matplotlib.pyplot as plt

# 1. 損失関数（山の地形）: f(x, y) = x^2 + y^2
# 目標は (0, 0) にたどり着くこと
def loss_function(x, y):
    return x**2 + y**2

# 2. 勾配の計算（足元の傾斜）
# f(x, y) を x と y でそれぞれ偏微分します
def calculate_gradient(x, y):
    grad_x = 2 * x  # x^2 の微分
    grad_y = 2 * y  # y^2 の微分
    return grad_x, grad_y

# 3. 勾配降下法の実装
def gradient_descent(start_x, start_y, learning_rate, iterations):
    # 履歴を保存するリスト（可視化用）
    path_x = [start_x]
    path_y = [start_y]

    x = start_x
    y = start_y

    for i in range(iterations):
        # 今の場所の傾きを計算
        grad_x, grad_y = calculate_gradient(x, y)

        # 傾きと逆方向へ「学習率」分だけ進む
        # x_new = x - (学習率 * 傾き)
        x = x - learning_rate * grad_x
        y = y - learning_rate * grad_y

        path_x.append(x)
        path_y.append(y)

    return path_x, path_y

# --- 設定 ---
start_x, start_y = -8.0, 6.0  # スタート地点（山の上）
learning_rate = 0.1           # 歩幅（学習率）
iterations = 20               # 何歩進むか

# --- 実行 ---
